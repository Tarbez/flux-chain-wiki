/* DEFXN home mockup: the Measured rail (2026-10-23, redesigned: owner, "redesign and enrich this,
   inspired by the rest of the page design").

   What DEFXN measures is its capabilities: the pieces dense-wire launches on chain with a
   derived manifest (attest, custody, ledger, signer...). Resolvers compose them; products are
   surfaces. The list is derived (capabilities-data.js, generated by make-capabilities.mjs from the
   manifests), so a newly launched capability appears here on the next run with no page edit.

   Three parts, top to bottom:
     the fleet run   BENCH-013's four figures as tiles, each named by what it counts, with the
                     run's date and size. The "ops/s" figure is in no record; the owner decides.
     capabilities    one strip that splits the checked cases among the capabilities (the stacked
                     block of the owner's boards, flat), and a grid of all of them, most checked
                     cases first, so none needs scrolling; a pick shows one in focus
     in focus        the brief's plain words for it, its checked cases, two of their names, and
                     its speed: not measured yet (said, never shown as 0)
   Motion: the rail enters with the page (app.js). Picking a capability lights its tile and its
   strip segment and wipes the focus in; nothing moves on its own. */
(function () {
  'use strict';
  var D = window.DEFXN_CAPABILITIES, rail = document.querySelector('.rail');
  if (!D || !rail) return;
  var esc = window.DEFXNKitUI ? window.DEFXNKitUI.esc : function (s) { return String(s); };
  var $ = function (name) { return rail.querySelector('[data-cap="' + name + '"]'); };
  var caps = D.capabilities.slice().sort(function (a, b) { return b.count - a.count || (a.id < b.id ? -1 : 1); });
  var fmt = new Intl.NumberFormat('en-US');
  var total = caps.reduce(function (s, c) { return s + c.count; }, 0);
  var most = caps[0] ? caps[0].count : 1;
  function title(id) { return id.charAt(0).toUpperCase() + id.slice(1); }
  /* what each fleet figure counts, in plain words */
  var COUNTS = { 'ops/s': 'All operations', 'swaps/s': 'Swaps', 'transfers/s': 'Transfers', 'records/s': 'Stored results' };

  $('summary').textContent = '';   /* the fleet's own line carries its date; the footer says devnet */
  var run = D.runs && D.runs.filter(function (r) { return r.id === D.fleet.run; })[0];
  $('fleet').innerHTML = '<div class="rx-row"><h3 class="mono">The fleet</h3><span class="rx-src mono">' + esc(D.fleet.run) + '</span></div>' +
    '<dl class="rx-tiles">' + D.fleet.figures.map(function (f) {
      return '<div><dt>' + esc(COUNTS[f.unit] || f.name) + '</dt><dd><b>' + fmt.format(f.value) + '</b><span>' + esc(f.unit) + '</span></dd></div>';
    }).join('') + '</dl>' +
    '<p class="rx-when mono">One run · ' + D.fleet.nodes + ' nodes' + (run ? ' · ' + esc(run.date) : '') + '</p>';
  if (!$('list')) return;   /* home shows the fleet only (record descent, 2026-10-24); the capability grid lives on #/measured */
  $('count').textContent = caps.length + ' · ' + total + ' checked cases';
  /* the strip: each capability's share of all checked cases, a 2px gap between segments */
  $('stack').innerHTML = caps.map(function (c) {
    return '<i data-seg="' + c.id + '" style="flex:' + c.count + ' 1 0"></i>';
  }).join('');
  /* the grid: every capability, most checked cases first; the bar is its cases against the most */
  $('list').innerHTML = caps.map(function (c) {
    return '<li><button type="button" data-cap-id="' + c.id + '" aria-pressed="false" aria-label="' + esc(title(c.id) + ', ' + c.count + ' checked cases') + '">' +
      '<span class="rx-n">' + esc(title(c.id)) + '</span><span class="rx-c">' + c.count + '</span>' +
      '<span class="rx-bar" aria-hidden="true"><i style="width:' + Math.max(6, Math.round(c.count / most * 100)) + '%"></i></span></button></li>';
  }).join('');

  function show(id, wipe) {
    var c = caps.filter(function (x) { return x.id === id; })[0] || caps[0];
    rail.querySelectorAll('[data-cap-id]').forEach(function (b) { b.setAttribute('aria-pressed', b.dataset.capId === c.id); });
    rail.querySelectorAll('[data-seg]').forEach(function (s) { s.classList.toggle('on', s.dataset.seg === c.id); });
    var f = $('focus');
    f.innerHTML = '<p class="rx-kicker mono">In focus' + (c.version ? ' · v' + esc(c.version) : '') + '</p>' +
      '<h2 class="rx-name">' + esc(title(c.id)) + '</h2>' +
      '<p class="rx-line">' + esc(c.plain || 'The brief has no plain words for it yet.') + '</p>' +
      '<dl class="rx-facts"><div><dt>Checked cases</dt><dd>' + c.count + ' <span>of ' + total + '</span></dd></div>' +
      '<div><dt>Speed</dt><dd class="rx-none">Not measured yet</dd></div></dl>' +
      (c.cases.length ? '<ul class="rx-cases">' + c.cases.slice(0, 1).map(function (x) { return '<li>' + esc(x) + '</li>'; }).join('') + '</ul>' : '');
    if (wipe) { f.classList.remove('swap'); void f.offsetWidth; f.classList.add('swap'); }
  }
  $('list').addEventListener('click', function (e) {
    var b = e.target.closest('[data-cap-id]'); if (b) show(b.dataset.capId, true);
  });
  /* start on the capability with the most checked cases */
  if (caps[0]) show(caps[0].id, false);
})();
