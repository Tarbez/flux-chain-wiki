'use strict';
/* The world grammar, locked (docs/design/world-grammar/CONTRACT.md, README.md). Owner-confirmed on screen 2026-10-29
   ("we are good to go"); this file measures exactly what was confirmed and nothing visual (workspace law: tests lock
   a confirmed design; no screenshots here).

   Why each block exists:
     1. every record in world/world.flx reads through js/world2/world-reader.mjs, the reader the atlas generated. The
        encoder refuses to write a record the reader refuses, so a record that fails here was written by something
        else, or the reader was regenerated over different labels than the records.
     2. the encoder is idempotent: run twice into two temp dirs it writes byte-identical files, and those files are
        byte-identical to what is under world/, js/world2/world-reader.mjs and docs/design/world-grammar/. A drift
        here means some order came from iteration, a name from a timestamp, or the checked-in output is stale.
     3. each WFRAME blob's byte count is the sum of its parts' instances times 64 (16 Float32 per instance), the file
        on disk has that many bytes, and every WPART's offset plus its count times 64 fits inside the blob: a part
        past the end is a draw that reads nothing.
     4. the atlas audit over the labels has zero findings that need a person: the reader is generated over labels
        that cannot capture one another.
     5. the card's records (world/card.flx, MESH.md) read through the card's OWN reader, js/world2/card-reader.mjs,
        and each MESH blob on disk has exactly the A bytes its record claims; each TEX names a file. Until 2026-10-29
        this block read card.flx through the world reader; the owner then ruled "do not compound on one grammar only;
        build a grammar for each thing in isolation to maintain speed", so the card got its own reader (generated by
        scripts/card-grammar-build.mjs from scripts/lib/card-grammar.mjs) and the world's W set lost MESH, TEX and
        PLACE. That is a reader swap, not a design change: the confirmed design (every record reads through a
        generated reader, blobs sized as recorded) is what this block still measures.
   Nothing else: the look, the camera, the frame time are the browser check's (scratchpad world2-check.mjs). */
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const { spawnSync } = require('node:child_process');

const SITE = path.join(__dirname, '..');
const ENCODER = path.join(SITE, 'scripts', 'world-encode.mjs');
const READER = path.join(SITE, 'js', 'world2', 'world-reader.mjs');
const FLX = path.join(SITE, 'world', 'world.flx');
const CARD = path.join(SITE, 'world', 'card.flx');
const CARD_READER = path.join(SITE, 'js', 'world2', 'card-reader.mjs');   /* the card's own reader (block 5) */
const INSTANCE_BYTES = 64;

/* the paths the encoder writes, relative to its output root (CONTRACT.md "Files and owners") */
function outputs(root) {
  const text = fs.readFileSync(path.join(root, 'world', 'world.flx'), 'utf8');
  const cids = [];
  for (const line of text.split('\n')) {
    const m = /-C([0-9a-f]{64})/.exec(line);
    if (m) cids.push({ cid: m[1], image: /^W(MARK|LOGO)-/.test(line) });
  }
  const files = ['world/world.flx', 'js/world2/world-reader.mjs', 'docs/design/world-grammar/world-reader.mjs', 'docs/design/world-grammar/world-grammar.labels.json'];
  const seen = new Set();
  for (const { cid, image } of cids) {
    if (seen.has(cid)) continue; seen.add(cid);
    const named = fs.readdirSync(path.join(root, 'world')).filter((f) => f.startsWith(cid + '.'));
    assert.equal(named.length, 1, `exactly one file named by content id ${cid} under ${root}/world (found ${named.join(', ') || 'none'})`);
    assert.equal(/\.(png|svg)$/.test(named[0]), image, `${named[0]}: an image record names an image file and a frame record names a .bin`);
    files.push('world/' + named[0]);
  }
  return files;
}

(async () => {
  /* ---- 1. every record reads ---- */
  const reader = await import(pathToFileURL(READER).href);
  const lines = fs.readFileSync(FLX, 'utf8').split('\n').filter((l) => l.length);
  assert.ok(lines.length > 100, `world.flx holds the whole world (${lines.length} records)`);
  for (const line of lines) {
    assert.match(line, /^[\x21-\x7e]+$/, `printable ASCII, no spaces: ${line}`);
    let boxes;
    assert.doesNotThrow(() => { boxes = reader.readRecord(line); }, `the reader reads: ${line}`);
    assert.equal(boxes[0].label, 'W', `the first box is the record kind: ${line}`);
  }
  const kinds = new Set(lines.map((l) => l.split('-')[0]));
  for (const k of ['WRING', 'WCUBE', 'WLABEL', 'WKNOB', 'WVIEW', 'WEXIT', 'WMARK', 'WLOGO', 'WFRAME', 'WPART']) assert.ok(kinds.has(k), `${k} records are present`);
  console.log(`1. ${lines.length} records read through the generated reader`);

  /* ---- 2. idempotent, and identical to what is checked in ---- */
  const runs = [0, 1].map((i) => {
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'world-grammar-' + i + '-'));
    const run = spawnSync(process.execPath, [ENCODER], { cwd: SITE, encoding: 'utf8', env: Object.assign({}, process.env, { WORLD_OUT: dir }) });
    assert.equal(run.status, 0, `the encoder ran into ${dir}:\n${run.stdout}${run.stderr}`);
    return dir;
  });
  const [a, b] = runs.map(outputs);
  assert.deepEqual(a, b, 'both runs wrote the same set of files');
  for (const rel of a) {
    const x = fs.readFileSync(path.join(runs[0], rel)), y = fs.readFileSync(path.join(runs[1], rel)), z = fs.readFileSync(path.join(SITE, rel));
    assert.ok(x.equals(y), `${rel}: byte-identical across two runs`);
    assert.ok(x.equals(z), `${rel}: byte-identical to what is checked in under the site`);
  }
  runs.forEach((dir) => fs.rmSync(dir, { recursive: true, force: true }));
  console.log(`2. the encoder is idempotent: ${a.length} files byte-identical across two runs and the site`);

  /* ---- 3. frames and parts ---- */
  const frames = {}, parts = {};
  for (const line of lines) {
    const b = Object.fromEntries(reader.readRecord(line).map((x) => [x.label, x.value]));
    if (b.W === 'FRAME') frames[b.R] = { cid: b.C, bytes: Number(b.A) };
    if (b.W === 'PART') (parts[b.R] || (parts[b.R] = [])).push({ part: b.M, offset: Number(b.O), count: Number(b.A) });
  }
  const views = Object.keys(frames);
  assert.ok(views.length >= 4, `frames for the slice-1 views (${views.join(', ')})`);
  for (const view of views) {
    const f = frames[view], ps = parts[view] || [];
    assert.ok(ps.length, `${view}: has parts`);
    const sum = ps.reduce((n, p) => n + p.count * INSTANCE_BYTES, 0);
    assert.equal(f.bytes, sum, `${view}: the blob's byte count is the sum of its parts' instances x 64`);
    assert.equal(fs.statSync(path.join(SITE, 'world', f.cid + '.bin')).size, f.bytes, `${view}: the blob file has A bytes`);
    for (const p of ps) {
      assert.equal(p.offset % INSTANCE_BYTES, 0, `${view}/${p.part}: the offset is on an instance boundary`);
      assert.ok(p.offset + p.count * INSTANCE_BYTES <= f.bytes, `${view}/${p.part}: offset ${p.offset} + ${p.count} x 64 fits in ${f.bytes}`);
    }
    const names = ps.map((p) => p.part);
    assert.equal(new Set(names).size, names.length, `${view}: one WPART per part`);
  }
  console.log(`3. ${views.length} frames: bytes = parts x 64, every part inside its blob`);

  /* ---- 4. the atlas audit ---- */
  const enc = await import(pathToFileURL(ENCODER).href);
  const { GC, REG } = enc.loadAtlas();
  const L = enc.labels(enc.loadNetwork());
  assert.doesNotThrow(() => enc.audit(GC, REG, L), 'the atlas audit over the labels finds nothing a person must read');
  const readerLabels = reader.LABELS.map((l) => l.label).sort().join('');
  assert.equal(L.map((l) => l.letter).sort().join(''), readerLabels, 'the generated reader carries exactly the encoder\'s labels');
  assert.deepEqual(reader.LABELS.find((l) => l.label === 'M').values, enc.PARTS, 'the mesh parts of the reader are the encoder\'s parts, in order');
  console.log(`4. atlas audit: ${L.length} labels, zero findings`);

  /* ---- 5. the card's records through the card's own reader ---- */
  const cardReader = await import(pathToFileURL(CARD_READER).href);
  const cardLines = fs.readFileSync(CARD, 'utf8').split('\n').filter((l) => l.length);
  assert.ok(cardLines.length >= 3, `card.flx holds MESH, TEX and PLACE records (${cardLines.length})`);
  let meshes = 0;
  for (const line of cardLines) {
    let b;
    assert.doesNotThrow(() => { b = Object.fromEntries(cardReader.readRecord(line).map((x) => [x.label, x.value])); }, `the card reader reads: ${line}`);
    if (b.W === 'MESH') { meshes++; assert.equal(fs.statSync(path.join(SITE, 'world', b.C + '.mesh')).size, Number(b.A), `${b.R}: the mesh blob has A bytes`); }
    if (b.W === 'TEX') assert.ok(fs.existsSync(path.join(SITE, 'world', b.C + '.jpg')), `texture ${b.C}.jpg exists`);
  }
  assert.ok(meshes >= 1, 'at least one MESH record');
  console.log(`5. card.flx: ${cardLines.length} records read through the card's own reader, ${meshes} mesh blob(s) sized as recorded`);
  console.log('world-grammar: ok');
})().catch((e) => { console.error(e && e.stack || e); process.exit(1); });
