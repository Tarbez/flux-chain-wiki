/* The home page treats colour as data (docs/brand/DEFXN.md, "Home: colour as data").

   Named regressions, each one something the page shipped before 2026-10-14:
   - the headline's second and third lines were painted in the identity colour,
     a large area of hue that said nothing about any data;
   - the hero illustration filled seven tiles with -200/-300/-400 role shades,
     muddy mid-saturation browns, so no single record stood out;
   - the benchmark numbers were painted in the identity colour;
   - "Run DEFXN" in the header was a dark secondary-100 fill, a second
     semi-saturated action competing with the one main CTA;
   - the selected audience tab was a full secondary-colour block, a large area
     of a bright accent.
   Each would look fine in a screenshot, which is how they shipped.

   Since the owner confirmed the 3D world home on 2026-10-27 (js/pages/home.js, css/world-pages.css), the
   rules are measured on the world home's sheet as well as on css/home-swiss.css (still loaded on every page):
   - one filled action on the page (the rail's .cta), the main action an outline (.cta.quiet): no second
     semi-saturated action competes;
   - the identity colour is spent on those actions and on the heading's accent row only; the rail's figures,
     the selected capability and the paths stay neutral;
   - no -100..-400 role shade on the world home either.
   Superseded by the owner's confirmed design: the heading's LAST row is the accent (js/pages/home.js "the last
   row is the accent", css/world-pages.css .home-world h1 span). That is one row, not "the second and third
   lines"; it is held to one row below, and the figures stay monochrome. */
'use strict';
const assert = require('node:assert/strict');
const fs = require('node:fs');

const home = fs.readFileSync('css/home-swiss.css', 'utf8');
const components = fs.readFileSync('css/components.css', 'utf8');
const themes = fs.readFileSync('css/flux-themes.css', 'utf8');
const rules = [...home.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map(([, sel, body]) => ({ sel: sel.trim(), body }));

// Saturation compression: the home page uses neutrals and role bases only.
const shades = home.match(/var\(--(primary|secondary|reference)-[1-4]00\)/g) || [];
assert.deepEqual(shades, [], 'css/home-swiss.css must not paint with -100..-400 role shades: they are the muddy middle of the saturation range');

// The identity colour marks only the record whose state changes, and what points at it.
const allowed = /land-accent|land-head-dot|land-resolution|land-key-accent|hl-record-study/;
for (const { sel, body } of rules) {
  if (!/var\(--primary\)/.test(body)) continue;
  assert(allowed.test(sel), `"${sel.slice(0, 80)}" paints with the identity colour, but it is not the record in flight or a mark that points at it`);
}
for (const { sel, body } of rules) {
  if (/hl-title|hl-metric/.test(sel)) assert(!/var\(--(primary|secondary|reference)/.test(body), `"${sel.slice(0, 80)}" colours a headline or a number; they stay monochrome`);
}

// Gravity and luminance are derived tokens, present in every palette.
const palettes = (themes.match(/^\/\* \w+ (dark|light) · /gm) || []).length;
assert.equal(palettes, 10, 'five families, dark and light');
for (const token of ['--primary-scale:', '--secondary-scale:', '--reference-scale:', '--anchor:', '--anchor-ink:'])
  assert.equal(themes.split(token).length - 1, palettes, `every palette declares ${token} (generated by scripts/build-flux-themes.cjs)`);
const scales = [...themes.matchAll(/--secondary-scale:([\d.]+);/g)].map((m) => +m[1]);
assert(scales.every((s) => s >= .72 && s <= 1), 'accent scales stay within 0.72..1');
assert(Math.min(...scales) < Math.max(...scales), 'the scale follows luminance: bright and dark accents must not get the same size');

// The world home (owner-confirmed 2026-10-27): one filled action, the rail's; the main action is the outline.
// (Before, js/pages/home.js was a page of Ark blocks with one tone: 'primary' button.)
const homeJs = fs.readFileSync('js/pages/home.js', 'utf8');
const ctas = [...homeJs.matchAll(/node\('a', '(cta[^']*)'\)/g)].map((m) => m[1]);
assert.deepEqual(ctas.sort(), ['cta quiet rise', 'cta small rail-cta'], 'the world home builds two actions: the outlined main one and the rail\'s');
assert.equal(ctas.filter((c) => !/\bquiet\b/.test(c)).length, 1, 'one filled action on the home page');
const world = fs.readFileSync('css/world-pages.css', 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const worldRules = [...world.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map(([, sel, body]) => ({ sel: sel.trim().replace(/^@[^{]*\{\s*/, ''), body }))
  .filter(({ sel }) => /\.world-page|\.home-world|\.rx-|\.rail/.test(sel));
assert.deepEqual(world.match(/var\(--(primary|secondary|reference)-[1-4]00\)/g) || [], [], 'css/world-pages.css must not paint with -100..-400 role shades');
const worldAllowed = /^\.world-page \.cta(\.quiet)?$|^\.home-world h1 span$/;
for (const { sel, body } of worldRules) {
  if (!/var\(--(primary|secondary|complement|accent)\)/.test(body)) continue;
  assert(worldAllowed.test(sel), `"${sel.slice(0, 80)}" paints the world home with the identity colour, but it is not an action or the heading's accent row`);
}
assert(/\.home-world h1 span \{[^}]*var\(--primary\)/.test(world) && /h1\.appendChild\(node\(i === rows\.length - 1 && rows\.length > 1 \? 'span' : 'b'/.test(homeJs), 'the accent is the heading\'s last row only');
for (const sel of ['.rx-tiles b', '.rx-facts dd', '.rx-grid button[aria-pressed="true"]', '.home-world .paths b'])
  assert(worldRules.some((r) => r.sel === sel) && worldRules.filter((r) => r.sel === sel).every((r) => !/var\(--(primary|secondary|complement|accent)/.test(r.body)), `${sel} stays neutral (numbers and selections are not painted)`);
assert(!/\.ark-|hl-button|hl-audience-tab/.test(home), 'css/home-swiss.css repaints no Ark block and no old home control');
assert(!/hl-audience-tab\[aria-selected="true"\] \{[^}]*--secondary/.test(components), 'the selected audience tab is not a block of action colour');
// The home page keeps the site's own nav (the one every other page shows): no home-only header rules.
assert(!/data-page="zero"\] \.(ark-header|header-|nav-toggle)/.test(home + components), 'the home page does not restyle the shared nav');

// Heavy bases: the scene's readout sits on the anchor (the old hero strip and closing went with the
// hand-built home; the fleet signal is an Ark stat tile now).
for (const sel of ['.land-panel-heavy {'])
  assert(new RegExp(sel.replace(/[.*+?^${}()|[\]\\]/g, '\\$&') + '[^}]*var\\(--anchor\\)').test(home), `${sel} sits on the anchor neutral`);

// The two brand marks are generated masks, painted with currentColor so they take the ink of
// every palette. Since 2026-10-19 the product kit is their canonical home (defxn-product-kit
// brand/marks, emitted as defxn-marks.data.css and synced into assets/kit/); this site loads
// that file. Named regression: a CSS mask loaded from file:// is blocked as cross-origin, so
// the marks must be embedded, not linked.
const marks = fs.readFileSync('assets/kit/defxn-marks.data.css', 'utf8');
assert(/<link rel="stylesheet" href="assets\/kit\/defxn-marks\.data\.css[?"]/.test(fs.readFileSync('index.html', 'utf8')), 'index.html loads the kit\'s data: marks');
for (const name of ['defxn', 'fxn']) assert(new RegExp('--mark-' + name + ':url\\("data:image/png;base64,').test(marks), `--mark-${name} is embedded as a data: URI`);
assert(/\.brand-mark \{[^}]*background:currentColor/.test(marks), 'marks are painted with currentColor');
assert(!/url\((?!"data:)/.test(marks), 'no mark is loaded by file path');
/* Since 2026-10-19 the header is the family bar (DefxnKit.mountShell, js/resolvers/header.js):
   its .dx-mark is masked by --dx-mark, which the data: marks sheet points at the DEFXN mark, so
   the bar's mark is the same embedded PNG (it must still open on file://). */
assert(/DefxnKit|kit\.mountShell\(\{ mode: 'home'/.test(fs.readFileSync('js/resolvers/header.js', 'utf8')), 'the header is the family bar');
assert(/--dx-mark:var\(--mark-defxn\)/.test(marks), 'the bar\'s mark is the embedded DEFXN mark');
assert(/\.dx-mark \{[^}]*mask: var\(--dx-mark\)/.test(fs.readFileSync('assets/kit/defxn-components.css', 'utf8')), 'the bar paints the mark through --dx-mark');
assert(/\.land-coin \{[^}]*--mark-fxn/.test(home), 'FXN amounts in the landscape carry the FXN coin mark');
console.log('PASS: home colour is data — neutrals plus role bases only, identity colour on the record in flight, ' +
  'one filled action on the world home with the identity colour on its actions and one heading row only, ' +
  'monochrome numbers, luminance-scaled action, anchored bases in all ' + palettes + ' palettes.');
