  function rootStyle() { return window.getComputedStyle(document.documentElement); }
  /* A custom property's value, following var() references (a browser substitutes them; jsdom leaves them). */
  function resolve(name, depth) {
    var v = String(rootStyle().getPropertyValue('--' + name) || '').trim();
    var m = /^var\(\s*--([\w-]+)\s*(?:,([\s\S]*))?\)$/.exec(v);
    if (m && depth < 8) { var next = resolve(m[1], depth + 1); return next || (m[2] || '').trim(); }
    return v;
  }
  /* "H S% L%" channels -> [r,g,b] 0..255; null for a token with alpha (a border tint has no single contrast) or no reading. */
  function rgb(name) {
    var v = resolve(name, 0).replace(/^hsla?\(|\)$/g, '').trim();
    var m = /^(-?[\d.]+)(?:deg)?[\s,]+([\d.]+)%[\s,]+([\d.]+)%(?:\s*[\/,]\s*([\d.]+)(%?))?$/.exec(v);
    if (!m) return null;
    if (m[4] != null && (m[5] ? Number(m[4]) / 100 : Number(m[4])) < 1) return null;
    var h = ((Number(m[1]) % 360) + 360) % 360, sat = Number(m[2]) / 100, l = Number(m[3]) / 100;
    var c = (1 - Math.abs(2 * l - 1)) * sat, x = c * (1 - Math.abs((h / 60) % 2 - 1)), k = l - c / 2, t;
    if (h < 60) t = [c, x, 0]; else if (h < 120) t = [x, c, 0]; else if (h < 180) t = [0, c, x]; else if (h < 240) t = [0, x, c]; else if (h < 300) t = [x, 0, c]; else t = [c, 0, x];
    return t.map(function (n) { return Math.round((n + k) * 255); }); /* 8-bit channels, as the screen and the SDK's own contrastRatio draw them */
  }
  /* WCAG 2.x relative luminance and contrast ratio. */
  function luminance(c) {
    var lin = c.map(function (n) { n = n / 255; return n <= 0.03928 ? n / 12.92 : Math.pow((n + 0.055) / 1.055, 2.4); });
    return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2];
  }
  function ratio(fg, bg) {
    var a = rgb(fg), b = rgb(bg);
    if (!a || !b) return null;
    var la = luminance(a), lb = luminance(b);
    return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
  }
  /* The ratio, floored to two places (4.499 must never read as 4.5), with the WCAG level it reaches. */
  function reading(fg, bg) {
    var r = ratio(fg, bg);
    if (r == null) return null;
    var level = r >= 7 ? 'AAA' : r >= 4.5 ? 'AA' : r >= 3 ? 'Large text and edges' : 'Below 3';
    return (Math.floor(r * 100) / 100).toFixed(2) + ' · ' + level;
  }
  function onCanvas(token) { var r = ratio(token, 'canvas'); return r == null ? '' : (Math.floor(r * 100) / 100).toFixed(2) + ':1 on canvas'; }

