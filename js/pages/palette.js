  /* Every Ark UI part (the owner, 2026-10-24: "we need all the primitive Ark UI examples shown"). The blocks come from Ark UI's
     own registry (ArkKit.describeArkBlocks) and each draws its own example (js/ark/vendor/ark-kit-examples.js, loaded only
     here: the public kit drops the examples to keep every other page light). They are grouped by Ark UI's categories, so a
     block Ark UI adds shows here with nothing listed by hand. The forms, popover and figures chunks register their blocks
     first. Each group is one tab; a group longer than the screen scrolls inside its own box. */
  function partsFigure() {
    var box = document.createElement('div'), note = document.createElement('p'), B = ArkUI.blocks;
    box.className = 'palette-parts'; note.className = 'palette-parts-note'; note.textContent = 'Loading every Ark UI part.';
    box.appendChild(note);
    [B.formsScript, B.popoverScript, B.figuresScript, 'js/ark/vendor/ark-kit-examples.js'].reduce(function (chain, file) {
      return chain.then(function () { return file ? ArkUI.loadScript(file) : null; });
    }, Promise.resolve()).then(function () {
      if (B.sync) B.sync();
      var examples = (window.ArkKitExamples && ArkKitExamples.ARK_BLOCK_EXAMPLES) || {}, groups = {}, order = [];
      ArkKit.describeArkBlocks().forEach(function (d) {
        if (!examples[d.name]) return;
        var c = d.category || 'other';
        if (!groups[c]) { groups[c] = []; order.push(c); }
        groups[c].push(d.name);
      });
      box.replaceChildren(B.render({ block: 'tabs', id: 'palette-parts-groups', props: { label: 'Ark UI part groups', variant: 'segmented', items: order.map(function (c) {
        return { value: c, label: c.charAt(0).toUpperCase() + c.slice(1) + ' ' + groups[c].length, blocks: [].concat.apply([], groups[c].map(function (name) {
          return [{ block: 'section-header', props: { title: name, level: 3 } }, { block: name, id: 'palette-part-' + name, props: examples[name] }];
        })) };
      }) } }));
    }).catch(function (error) {
      note.textContent = 'The parts did not load (' + error.message + '). Reload the page to try again.';
    });
    return box;
  }

  function slots() {
    var out = { components: components, neutrals: neutrals, meaning: meaning, borders: borders, 'type-slots': slotsFigure, 'type-scale': scaleFigure, parts: partsFigure };
    ROLES.forEach(function (entry) {
      out['shades-' + entry[0]] = function () { return shades(entry[0]); };
      out['tones-' + entry[0]] = function () { return tones(entry[0]); };
    });
    return out;
  }

  ArkUI.pageModules.palette = {
    spec: spec,
    mount: function (host) {
      var page = ArkUI.page(spec(familyName()), host, {
        page: 'palette', className: 'palette-page', titleId: 'palette-title', slots: slots(),
        actions: {
          /* The settings panel chooses the theme this page shows (its "See the full palette" leads here). */
          'open-theme-settings': function () {
            var trigger = document.querySelector('.settings-trigger');
            if (trigger && trigger.getAttribute('aria-expanded') !== 'true') trigger.click();
            if (trigger) trigger.focus();
          }
        }
      });
      /* The active theme follows a theme switch without a remount: its name, every reading computed from its values
         (the contrast tables, the meaning swatches' ratios) and the scale's sizes, which also follow the screen. */
      var family = page.querySelector('#palette-hero [data-ark-part="hero-meta"] dd');
      /* The readings move in place: the same table, the same cells, new words. (The shape never changes with a theme, so there
         is nothing for Ark's live patch to reshape, and the page does not pay for its chunk.) */
      function paintTable(id, props) {
        var table = page.querySelector('#' + id);
        if (!table) return;
        Array.prototype.forEach.call(table.querySelectorAll('tbody tr'), function (row, i) {
          props.columns.forEach(function (column, j) {
            var value = props.rows[i] && props.rows[i][column.key], cell = row.children[j];
            if (cell && j > 0) cell.textContent = value == null ? 'No reading' : value;
          });
        });
      }
      function paintTheme() {
        if (family) family.textContent = familyName();
        Array.prototype.forEach.call(page.querySelectorAll('[data-palette-ratio]'), function (small) { small.textContent = onCanvas(small.getAttribute('data-palette-ratio')); });
        paintTable('palette-contrast-text', textTableProps());
        paintTable('palette-contrast-roles', roleTableProps());
        paintSlots(page); paintScale(page);
      }
      var observer = typeof MutationObserver !== 'undefined' ? new MutationObserver(paintTheme) : null;
      if (observer) observer.observe(document.documentElement, { attributes: true, attributeFilter: ['data-theme'] });
      var frame = 0;
      function onResize() { if (frame) return; frame = window.requestAnimationFrame(function () { frame = 0; paintScale(page); }); }
      if (window.requestAnimationFrame) window.addEventListener('resize', onResize);
      page.arkDispose = function () { if (observer) observer.disconnect(); window.removeEventListener('resize', onResize); };
      return page;
    }
  };
