/* Local page dependency loading, separate from route/presence state. */
(function () {
  'use strict';
  var scripts = new Map();
  var pageAssetVersion = '20261020-w5';
  /* A page script is served from its minified, mapped copy js/min/<same path under js/> when
     js/min/manifest.js (ArkUI.minScripts, generated by npm run build:ark; the rules are in
     scripts/lib/page-scripts.cjs) lists it, with the hash of that copy as its ?v= so the URL changes
     exactly when the bytes do. Any file the manifest does not list is requested as written, so an
     exempt or new file can never break a route. The commented source is read instead, never the
     copy, by jsdom (server rendering and the unit tests run the source: a render must not depend on a
     build output) and by a page opened with ?ark-source=1 (a developer reading code in the browser;
     the copies carry source maps too). */
  function readsSource() {
    if (typeof navigator !== 'undefined' && /jsdom/i.test(navigator.userAgent || '')) return true;
    return typeof location !== 'undefined' && /[?&]ark-source=1(?:&|$)/.test(location.search || '');
  }
  function scriptPath(url) {
    var key = url.slice(3, -3), served = ArkUI.minScripts;
    if (served && Object.prototype.hasOwnProperty.call(served, key) && !readsSource()) return 'js/min/' + key + '.js?v=' + served[key];
    return url + '?v=' + pageAssetVersion;
  }
  function loadScript(url) {
    if (!/^js\/(?:[a-z0-9-]+\/)*[a-z0-9-]+\.js$/.test(url)) return Promise.reject(new Error('Invalid page asset'));
    if (scripts.has(url)) return scripts.get(url);
    var promise = new Promise(function (resolve, reject) {
      var script = document.createElement('script');
      script.src = (location.protocol === 'file:' ? '' : '/') + scriptPath(url); script.async = true;
      script.onload = function () { resolve(); };
      script.onerror = function () { scripts.delete(url); script.remove(); reject(new Error('Could not load ' + url)); };
      document.head.appendChild(script);
    });
    scripts.set(url, promise);
    return promise;
  }
  /* Ark blocks (js/ark/blocks.js) need ArkUI.blockScripts loaded before the page mounts. A page
     built from blocks lists them in its own scripts (js/pages/catalog.js); this adds them, derived
     from the data, where nothing in the code can say so: a route (or the shell, '*') holding a
     saved Ark block instance, and every route in the editor's canvas, where the Library can
     insert one anywhere. The glossary comes with them where a saved block uses it ([[term]]
     markup or a term block) and in the canvas. Other routes never pay for either. */
  function inPreview() { return typeof location !== 'undefined' && /[?&]cms-preview=1(?:&|$)/.test(location.search || ''); }
  function savedBlocks(definition) {
    if (typeof ArkComponents === 'undefined' || !ArkComponents.get) return [];
    var data = ArkComponents.get(), prefix = 'ARK_BLOCK_', out = [];
    [definition.path, ArkComponents.SHELL].forEach(function (scope) {
      var anchors = (data.routes && data.routes[scope]) || {};
      Object.keys(anchors).forEach(function (anchor) {
        (anchors[anchor] || []).forEach(function (instance) {
          var master = data.masters && data.masters[instance.masterId];
          if (master && String(master.resolver || '').indexOf(prefix) === 0) out.push({ master: master, instance: instance });
        });
      });
    });
    return out;
  }
  function blockScriptsFor(definition) {
    var preview = inPreview(), saved = preview ? [] : savedBlocks(definition);
    if (!preview && !saved.length) return [];
    var glossary = preview || saved.some(function (entry) {
      return entry.master.resolver === 'ARK_BLOCK_TERM' || JSON.stringify([entry.master.props, entry.instance.overrides]).indexOf('[[') >= 0;
    });
    return (ArkUI.blockScripts || []).concat(glossary && ArkUI.glossaryScript ? [ArkUI.glossaryScript] : []);
  }
  function needsBlocks(definition) { return blockScriptsFor(definition).length > 0; }
  /* The optional blocks are not in the public kit: the form blocks (field, form, list, status-line, choice) are
     js/ark/vendor/ark-kit-forms.js and the popover is js/ark/vendor/ark-kit-popover.js and the lane and band are js/ark/vendor/ark-kit-figures.js; each registers into it
     (docs/cms-architecture.md Budget). A page that uses them lists the chunk itself; this adds them where nothing in
     the code can say so -- every route in the editor's canvas (the Library can insert any block anywhere), and a route
     whose saved Ark block has a resolver the loaded kit does not know: load a chunk, and ask again. Derived from the
     kit's own resolvers, never from a list of block names. */
  var OPTIONAL_CHUNKS = ['js/ark/vendor/ark-kit-forms.js', 'js/ark/vendor/ark-kit-popover.js', 'js/ark/vendor/ark-kit-figures.js'];
  function unknownSaved(definition) {
    var known = (ArkUI.blocks && ArkUI.blocks.resolvers) || [];
    return savedBlocks(definition).some(function (entry) { return known.indexOf(entry.master.resolver) < 0; });
  }
  /* Page stylesheets. index.html links the shared sheets; a page's own are listed on its catalog entry
     (`styles`, js/pages/catalog.js, derived by scripts/page-styles.mjs) and linked here, and the page
     mounts only after they have loaded, the way it waits for its scripts, so it is never painted bare.
     A late sheet is inserted at its place in the cascade (ArkUI.styleOrder), before the next sheet
     already linked, so css/components.css is still the last word, exactly as when index.html linked every
     sheet. Sheets stay once linked (a second visit costs nothing; a sheet only adds rules for classes
     the page it came for used). An entry with no `styles` list gets every sheet the shell does not link:
     right, but heavy, which is what scripts/page-styles.mjs --check exists to prevent.
     A sheet that cannot load never blocks the page (it shows unstyled, and the console says which), and
     neither does one that stalls: after STYLE_WAIT_MS the page mounts and the sheet applies when it lands. */
  var sheetPromises = new Map();
  var STYLE_WAIT_MS = 8000;
  function sheetFile(href) { return String(href || '').split('?')[0].split('#')[0].replace(/^(?:\.?\/)+/, ''); }
  function linkedSheet(file) {
    var links = document.querySelectorAll('link[rel~="stylesheet"]');
    for (var i = 0; i < links.length; i++) if (sheetFile(links[i].getAttribute('href')) === file) return links[i];
    return null;
  }
  function placeSheet(link, file) {
    var order = ArkUI.styleOrder || [], at = order.indexOf(file);
    for (var i = at + 1; at >= 0 && i < order.length; i++) {
      var later = linkedSheet(order[i]);
      if (later && later.parentNode) { later.parentNode.insertBefore(link, later); return; }
    }
    document.head.appendChild(link);
  }
  function loadSheet(file) {
    if (!/^(?:css|assets\/kit)\/[a-z0-9.-]+\.css$/.test(file)) return Promise.reject(new Error('Invalid page stylesheet'));
    if (sheetPromises.has(file)) return sheetPromises.get(file);
    if (linkedSheet(file)) return Promise.resolve();
    var promise = new Promise(function (resolve) {
      var link = document.createElement('link'), settled = false, timer = null;
      function settle(error) {
        if (settled) return;
        settled = true; clearTimeout(timer);
        if (error) {
          sheetPromises.delete(file); link.remove();
          if (window.console) console.error('[ark] stylesheet failed to load: ' + file + ' (' + error + '). The page shows without it; reloading may fix it.');
        }
        resolve();
      }
      link.rel = 'stylesheet';
      link.setAttribute('data-ark-style', file);
      link.href = (location.protocol === 'file:' ? file : '/' + file) + '?v=' + pageAssetVersion;
      link.onload = function () { settle(null); };
      link.onerror = function () { settle('network error'); };
      timer = setTimeout(function () { if (!settled) { settled = true; if (window.console) console.warn('[ark] stylesheet is slow: ' + file + '; mounting the page without waiting.'); resolve(); } }, STYLE_WAIT_MS);
      placeSheet(link, file);
    });
    sheetPromises.set(file, promise);
    return promise;
  }
  function stylesFor(definition) {
    if (definition.styles) return definition.styles;
    var shared = (ArkUI.pageStyles && ArkUI.pageStyles.shared) || [];
    return (ArkUI.styleOrder || []).filter(function (file) { return shared.indexOf(file) < 0; });
  }
  function loadStyles(definition) { return Promise.all(stylesFor(definition).map(loadSheet)); }
  async function loadPage(page, definition) {
    var styles = loadStyles(definition);
    styles.catch(function () {}); /* awaited below; a script failing first must not leave this unhandled */
    var blocks = blockScriptsFor(definition);
    for (var block of blocks) await loadScript(block);
    if (blocks.length) for (var chunk of OPTIONAL_CHUNKS) if (inPreview() || unknownSaved(definition)) await loadScript(chunk);
    var urls = definition.scripts;
    for (var url of urls) await loadScript(url);
    await styles;
    var module = ArkUI.pageModules[definition.module];
    if (!module) throw new Error('Page module missing: ' + page);
    return module;
  }
  ArkUI.loadPage = loadPage;
  ArkUI.loadStyles = loadStyles;
  ArkUI.pageNeedsBlocks = needsBlocks;
  /* One script by its site path, once (js/ark/blocks.js loads the live chunk through it). */
  ArkUI.loadScript = loadScript;
  /* One stylesheet by its site path, once, at its place in the cascade: the own sheet of a part a page shows only
     sometimes (js/ark/profile-card.js, the NFT card). scripts/page-styles.mjs counts a literal path passed here as used. */
  ArkUI.loadSheet = loadSheet;
})();
