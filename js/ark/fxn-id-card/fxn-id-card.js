// site: the attributes on <html> a theme, mode or skin change writes (js/bootstrap.js and the settings panel set data-theme)
const THEME_ATTRIBUTES = ['style', 'class', 'data-theme', 'data-theme-mode', 'data-chrome-skin']

const TEXT = 118
const BASE_ACCENT = [90, 255, 196]   // the accent as painted (sRGB), hue 158
const PLACEHOLDER = 'Your name'
const PACK_NAME = 'fxn-id-card.pack'
const BACK_SPEED = 1.6, CATCH_UP = 2.5

const clamp = (v, a = 0, b = 1) => Math.max(a, Math.min(b, v))
// site: 'blank' names frame 0, the plain card before its build lays a single plate (owner, 2026-10-31: the card is blank until
// you start, then builds itself piece by piece). A number is a frame. Every other name is a state of the timeline.
const BLANK = 0
const frameOf = (state) => typeof state === 'number' ? state : state === 'blank' ? BLANK : STATES[state]
const prog = (f, a, b) => clamp((f - a) / (b - a))
const easeOut = t => 1 - Math.pow(1 - t, 3)
const easeBack = t => 1 + 2.70158 * Math.pow(t - 1, 3) + 1.70158 * Math.pow(t - 1, 2)

// ---- the camera at a frame, by the player's own sampler rules
const easeOf = (c, t) => c === 1 ? t * t : c === 2 ? t * (2 - t) : c === 3 ? t * t * (3 - 2 * t) : c === 5 ? (t < 0.5 ? 4 * t * t * t : 1 - Math.pow(-2 * t + 2, 3) / 2) : t
const arc = (a, b) => (((b - a) % 360) + 540) % 360 - 180
export function cameraAt(frame) {
  if (frame <= CAM[0][0]) return camOf(CAM[0])
  const last = CAM[CAM.length - 1]
  if (frame >= last[0]) return camOf(last)
  let i = 0
  while (CAM[i + 1][0] <= frame) i++
  const A = CAM[i], B = CAM[i + 1]
  if (B[6] === 4) return camOf(A)
  const t = easeOf(B[6], (frame - A[0]) / (B[0] - A[0])), lerp = (a, b) => a + (b - a) * t
  return { aim: A[1].map((v, k) => lerp(v, B[1][k])), dist: Math.exp(lerp(Math.log(A[2]), Math.log(B[2]))), pitch: A[3] + arc(A[3], B[3]) * t, yaw: A[4] + arc(A[4], B[4]) * t, lens: lerp(A[5], B[5]) }
}
const camOf = k => ({ aim: k[1].slice(), dist: k[2], pitch: k[3], yaw: k[4], lens: k[5] })
// the view of a camera (fxn-3d engine/render/math.mjs eyeOf and view; anim-sample.mjs fovOf), with the page's orbit on top
export function viewOf(cam, W, H, orbit = { yaw: 0, pitch: 0 }) {
  const D = Math.PI / 180, e = clamp(cam.pitch + orbit.pitch, -89, 89) * D, y = (cam.yaw + orbit.yaw) * D, a = cam.aim
  const eye = [a[0] + cam.dist * Math.cos(e) * Math.sin(y), a[1] + cam.dist * Math.sin(e), a[2] + cam.dist * Math.cos(e) * Math.cos(y)]
  let z = [eye[0] - a[0], eye[1] - a[1], eye[2] - a[2]]; const zl = Math.hypot(...z); z = z.map(v => v / zl)
  let x = [z[2], 0, -z[0]]; const xl = Math.hypot(...x) || 1; x = x.map(v => v / xl)
  const u = [z[1] * x[2] - z[2] * x[1], z[2] * x[0] - z[0] * x[2], z[0] * x[1] - z[1] * x[0]]
  const f = cam.lens / 12   // 1 / tan(fov / 2), fov = 2 atan(12 / lens)
  const toView = p => { const d = [p[0] - eye[0], p[1] - eye[1], p[2] - eye[2]]; return [d[0] * x[0] + d[1] * x[1] + d[2] * x[2], d[0] * u[0] + d[1] * u[1] + d[2] * u[2], d[0] * z[0] + d[1] * z[1] + d[2] * z[2]] }
  const project = p => { const v = toView(p); return [(f * H / W * v[0] / -v[2] + 1) / 2 * W, (1 - f * v[1] / -v[2]) / 2 * H] }
  return { eye, x, u, z, f, fpx: f * H / 2, toView, project }
}
// the CSS matrix3d that takes a w x h box onto the quad q (top-left, top-right, bottom-right, bottom-left)
function boxOnto(w, h, q) {
  const [[x0, y0], [x1, y1], [x2, y2], [x3, y3]] = q
  const dx1 = x1 - x2, dx2 = x3 - x2, dy1 = y1 - y2, dy2 = y3 - y2, sx = x0 - x1 + x2 - x3, sy = y0 - y1 + y2 - y3
  const det = dx1 * dy2 - dx2 * dy1
  const g = (sx * dy2 - dx2 * sy) / det, hh = (dx1 * sy - sx * dy1) / det
  const a = x1 - x0 + g * x1, b = x3 - x0 + hh * x3, d = y1 - y0 + g * y1, e = y3 - y0 + hh * y3
  const m = [a / w, d / w, 0, g / w, b / h, e / h, 0, hh / h, 0, 0, 1, 0, x0, y0, 0, 1]
  return `matrix3d(${m.map(v => +v.toFixed(8)).join(',')})`
}

// ---- the accent: the hue-rotate and saturate that turn the painted accent into the theme's
const hueOf = ([r, g, b]) => { const mx = Math.max(r, g, b), mn = Math.min(r, g, b), c = mx - mn; if (!c) return null; const h = mx === r ? ((g - b) / c) % 6 : mx === g ? (b - r) / c + 2 : (r - g) / c + 4; return (h * 60 + 360) % 360 }
const satOf = ([r, g, b]) => { const mx = Math.max(r, g, b) / 255, mn = Math.min(r, g, b) / 255, l = (mx + mn) / 2; return mx === mn ? 0 : (mx - mn) / (1 - Math.abs(2 * l - 1)) }
function hueRotate([r, g, b], deg) {
  const t = deg * Math.PI / 180, c = Math.cos(t), s = Math.sin(t)
  return [
    r * (0.213 + c * 0.787 - s * 0.213) + g * (0.715 - c * 0.715 - s * 0.715) + b * (0.072 - c * 0.072 + s * 0.928),
    r * (0.213 - c * 0.213 + s * 0.143) + g * (0.715 + c * 0.285 + s * 0.140) + b * (0.072 - c * 0.072 - s * 0.283),
    r * (0.213 - c * 0.213 - s * 0.787) + g * (0.715 - c * 0.715 + s * 0.715) + b * (0.072 + c * 0.928 + s * 0.072)].map(v => clamp(v, 0, 255))
}
export function parseColour(text) {
  const n = (text.match(/-?[\d.]+/g) || []).map(Number)
  if (n.length < 3) return null
  return /color\(srgb/.test(text) ? n.slice(0, 3).map(v => v * 255) : n.slice(0, 3)
}
export function tintFor(accent) {
  if (!accent) return 'none'
  const sat = satOf(accent), hue = hueOf(accent)
  if (sat < 0.12 || hue == null) return 'saturate(0)'   // a grey accent: the strips glow white
  let best = 0, err = 1e9
  for (let d = 0; d < 360; d += 1) { const h = hueOf(hueRotate(BASE_ACCENT, d)); if (h == null) continue; const e = Math.min(Math.abs(h - hue), 360 - Math.abs(h - hue)); if (e < err) { err = e; best = d } }
  return `hue-rotate(${best}deg) saturate(${clamp(0.45 + sat * 0.75, 0.45, 1.2).toFixed(2)})`
}

let packBytes = null
async function loadPack() {
  if (packBytes) return packBytes
  const { default: b64 } = await import(PACK_URL)
  const raw = atob(b64), out = new Uint8Array(raw.length)
  for (let i = 0; i < raw.length; i++) out[i] = raw.charCodeAt(i)
  packBytes = out
  return out
}
// site: the sheet is awaited before the first tint, because the tint reads --fxn-idc-accent, which the sheet defines
let cssLinked = null
function linkStyles() {
  if (cssLinked) return cssLinked
  const link = document.createElement('link')
  link.rel = 'stylesheet'
  link.href = CSS_URL
  cssLinked = new Promise((done) => { link.onload = done; link.onerror = done; setTimeout(done, 3000) })
  document.head.appendChild(link)
  return cssLinked
}
const div = (cls, parent, text) => { const e = document.createElement('div'); e.className = cls; if (text != null) e.textContent = text; parent.appendChild(e); return e }

export function createFxnIdCard() {
  const styled = linkStyles()
  const el = document.createElement('div')
  el.className = 'fxn-idc'
  el.innerHTML = '<img class="fxn-idc-still" alt="" hidden><canvas class="fxn-idc-canvas"></canvas><span class="fxn-idc-probe"></span>'
  const still = el.querySelector('.fxn-idc-still'), canvas = el.querySelector('canvas'), probe = el.querySelector('.fxn-idc-probe')
  still.src = STILL_URL
  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)')
  const prints = {}
  const print = (name) => { const p = div('fxn-idc-print fxn-idc-print-' + name, el); prints[name] = p; return p }
  // the name plate: "FXN ID", a rule, the name
  const namePrint = print('name'), label = document.createElement('span'), rule = document.createElement('i'), nameEl = document.createElement('b')
  label.className = 'fxn-idc-label'; rule.className = 'fxn-idc-rule'; nameEl.className = 'fxn-idc-name'; namePrint.append(label, rule, nameEl)
  // the security plate: the PIN's grade, then the password's (four cells each)
  const lockPrint = print('lock'), pinBars = div('fxn-idc-bars', lockPrint), passBars = div('fxn-idc-bars fxn-idc-bars-seal', lockPrint)
  for (const bars of [pinBars, passBars]) for (let i = 0; i < 4; i++) div('fxn-idc-bar', bars)
  // the stamp: the chosen icon (ark-ui's own list, read from the kit at runtime, never a copy)
  const stampPrint = print('stamp'), svgNS = 'http://www.w3.org/2000/svg', svg = document.createElementNS(svgNS, 'svg'), iconPath = document.createElementNS(svgNS, 'path')
  svg.setAttribute('viewBox', '0 0 24 24'); svg.setAttribute('aria-hidden', 'true'); svg.appendChild(iconPath); stampPrint.appendChild(svg)
  // the vault on the back: one cell per recovery word, filled as each is confirmed
  const vaultPrint = print('vault'), vaultLabel = div('fxn-idc-label', vaultPrint, 'Recovery'), cells = div('fxn-idc-cells', vaultPrint)

  let player = null, mounting = null, failed = false, frame = BUILD, target = null, raf = 0, last = 0, observer = null, sizer = null, onFrame = null
  const values = { name: '', pinGrade: 0, passwordGrade: 0, icon: '', total: 24, picked: 0 }
  const orbitNow = { yaw: 0, pitch: 0 }
  let letters = []

  // ---- the prints: pure functions of the frame and the live values
  const put = (e, tf, op) => { const t = tf || 'none', o = op >= 0.999 ? '' : String(+clamp(op).toFixed(3)); if (e._t !== t) { e.style.transform = t; e._t = t } if (e._o !== o) { e.style.opacity = o; e._o = o } }
  const fade = (e, op) => { const o = op >= 0.999 ? '' : String(+clamp(op).toFixed(3)); if (e._o !== o) { e.style.opacity = o; e._o = o } }
  function setText(next = {}) { update({ name: next.name || '' }) }
  function update(next = {}) {
    if ('name' in next && String(next.name || '').trim() !== values.name) {
      values.name = String(next.name || '').trim()
      const text = values.name || PLACEHOLDER
      nameEl.textContent = ''
      nameEl.classList.toggle('is-placeholder', !values.name)
      nameEl.title = text
      letters = []
      // each word is one unbreakable run of letter spans, so a long name wraps between words, never inside one
      text.split(/(\s+)/).forEach((part) => {
        if (!part) return
        if (/^\s+$/.test(part)) { nameEl.appendChild(document.createTextNode(' ')); return }
        const word = document.createElement('span'); word.className = 'fxn-idc-word'; nameEl.appendChild(word)
        for (const ch of part) { const l = document.createElement('span'); l.textContent = ch; word.appendChild(l); letters.push(l) }
      })
    }
    for (const k of ['pinGrade', 'passwordGrade', 'total', 'picked']) if (k in next) values[k] = Number(next[k]) || 0
    if ('icon' in next && next.icon !== values.icon) {
      values.icon = next.icon || ''
      const icon = (window.ArkAdminAuth?.FXN_ID_ICONS || []).find(c => c.id === values.icon)
      iconPath.setAttribute('d', icon ? icon.path : '')
    }
    pinBars.dataset.grade = String(values.pinGrade); passBars.dataset.grade = String(values.passwordGrade)
    const n = values.total === 12 ? 12 : 24
    if (cells.childElementCount !== n) { cells.textContent = ''; cells.dataset.count = String(n); for (let i = 0; i < n; i++) div('fxn-idc-cell', cells) }
    Array.prototype.forEach.call(cells.children, (c, i) => { c.dataset.on = String(i < values.picked) })
    vaultLabel.textContent = values.picked ? `Recovery ${values.picked} / ${n}` : 'Recovery'
    renderPrints(frame)
  }
  function renderPrints(f) {
    const W = el.clientWidth, H = el.clientHeight
    if (!W || !H) return
    const view = viewOf(cameraAt(f), W, H, orbitNow)
    // each print shows from the moment its plate is in place; the plates part after master (the FXN ID view's open card)
    const show = { name: f >= TEXT && f <= STATES.master, lock: f >= 244 && f <= STATES.master, stamp: f >= 324 && f <= STATES.master, vault: f >= 404 && f < 466 }
    for (const [name, p] of Object.entries(prints)) {
      const F = FIELDS[name], [x0, y0, x1, y1] = F.box
      const facing = (view.eye[2] - F.z) * F.side   // the camera is on the face's side
      const at = (fx, fy) => view.project([(fx - 0.5) * CARD.W, (0.5 - fy) * CARD.H, F.z])
      const q = F.side > 0 ? [at(x0, y0), at(x1, y0), at(x1, y1), at(x0, y1)] : [at(x1, y0), at(x0, y0), at(x0, y1), at(x1, y1)]
      const w = Math.max(1, Math.round((Math.hypot(q[1][0] - q[0][0], q[1][1] - q[0][1]) + Math.hypot(q[2][0] - q[3][0], q[2][1] - q[3][1])) / 2))
      const h = Math.max(1, Math.round((Math.hypot(q[3][0] - q[0][0], q[3][1] - q[0][1]) + Math.hypot(q[2][0] - q[1][0], q[2][1] - q[1][1])) / 2))
      const on = show[name] && facing > 0.4
      p.hidden = !on
      if (!on) continue
      if (p._w !== w || p._h !== h) { p.style.width = w + 'px'; p.style.height = h + 'px'; p._w = w; p._h = h }
      p.style.transform = boxOnto(w, h, q)
    }
    // the build's type-on; later frames show it whole
    const n = clamp(Math.floor((f - TEXT) / 2), 0, 6), s = 'FXN ID'.slice(0, n)
    if (label._s !== s) { label.textContent = s; label._s = s }
    put(rule, `scaleX(${easeOut(prog(f, TEXT + 2, TEXT + 18)).toFixed(4)})`, 1)
    letters.forEach((l, i) => { const t = prog(f, TEXT + 8 + 1.2 * i, TEXT + 17 + 1.2 * i); put(l, t >= 1 ? null : `translateY(${(0.5 * (1 - easeBack(t))).toFixed(3)}em)`, t) })
    // a print's transform is its projection, so these set only opacity on the print and move what is inside it
    fade(lockPrint, prog(f, 244, 252)); put(passBars, `scaleY(${easeOut(prog(f, 284, 294)).toFixed(3)})`, prog(f, 284, 290))
    fade(stampPrint, prog(f, 324, 327)); put(svg, f < 334 ? `scale(${(1 + 0.6 * (1 - easeBack(prog(f, 324, 334)))).toFixed(3)})` : null, 1)
    fade(vaultPrint, prog(f, 404, 414) * (1 - prog(f, 450, 462)))
    if (onFrame) onFrame(f, view)
  }
  function retint() {
    probe.style.color = 'var(--fxn-idc-accent)'
    el.style.setProperty('--fxn-idc-tint', tintFor(parseColour(getComputedStyle(probe).color)))
  }

  // ---- the player
  async function mountPlayer() {
    if (player || failed) return player
    if (mounting) return mounting
    mounting = (async () => {
      const [{ mount }, bytes] = await Promise.all([import(PLAYER_URL), loadPack()])
      const realFetch = window.fetch
      window.fetch = (url, init) => (url === PACK_NAME ? Promise.resolve(new Response(bytes)) : realFetch.call(window, url, init))
      try { player = await mount(canvas, PACK_NAME, { drive: 'seek' }) }
      finally { window.fetch = realFetch }
      return player
    })().catch((error) => {
      failed = true   // no WebGL2, or the pack failed its check: the settled picture stands in, with the name
      console.warn('FXN ID card: the 3D card did not start, showing the still picture.', error?.message || error)
      return null
    }).finally(() => { mounting = null })
    return mounting
  }
  function showStill(on) { still.hidden = !on; canvas.hidden = on; el.dataset.still = String(on) }
  function seek(f) { frame = f; if (player) player.seek(f); renderPrints(failed ? BUILD : f) }
  function stopClock() { if (raf) cancelAnimationFrame(raf); raf = 0 }
  function tick(now) {
    const dt = last ? Math.min(0.05, (now - last) / 1000) : 1 / RATE; last = now
    if (target == null || frame === target) { raf = 0; return }
    const dir = Math.sign(target - frame), speed = dir < 0 ? BACK_SPEED : frame < BUILD && target > BUILD ? CATCH_UP : 1
    const step = Math.min(Math.abs(target - frame), dt * RATE * speed)
    seek(frame + dir * step)
    raf = frame !== target ? requestAnimationFrame(tick) : 0
  }
  function run() { if (!raf) { last = 0; raf = requestAnimationFrame(tick) } }

  function go(state) {
    const f = frameOf(state)
    if (f == null) return
    target = clamp(f, 0, LAST)
    if (!player || reduced.matches) { stopClock(); seek(target); return }
    run()
  }
  async function attach(host, opts = {}) {
    if (el.parentNode !== host) host.appendChild(el)
    update(opts)
    await styled
    if (el.parentNode !== host) return
    retint()
    if (!observer) {
      observer = new MutationObserver(retint)
      observer.observe(document.documentElement, { attributes: true, attributeFilter: THEME_ATTRIBUTES })
    }
    if (!sizer) { sizer = new ResizeObserver(() => renderPrints(failed ? BUILD : frame)); sizer.observe(el) }
    const play = opts.play && !reduced.matches
    const goal = opts.state != null ? frameOf(opts.state) ?? BUILD : BUILD
    // site: the still is the finished card, so a card that stands before its build (blank) waits on an empty canvas instead
    if (!player && !failed) { frame = play ? 0 : goal; showStill(!play && goal >= BUILD); renderPrints(frame) }
    const p = await mountPlayer()
    if (el.parentNode !== host) return
    if (!p) { showStill(true); seek(BUILD); return }
    showStill(false)
    seek(frame)   // the player starts at its range's first frame: draw the frame the page already stands on
    if (play && frame === 0) { target = goal; run(); return }
    go(goal)
  }
  function release() {
    stopClock(); target = null
    observer?.disconnect(); observer = null
    sizer?.disconnect(); sizer = null
    if (player) {
      player.stop()
      try { canvas.getContext('webgl2')?.getExtension('WEBGL_lose_context')?.loseContext() } catch {}
      player = null
    }
    el.remove()
  }
  function orbit(yaw, pitch = 0) { orbitNow.yaw = yaw; orbitNow.pitch = pitch; if (player) player.orbit(yaw, pitch); seek(frame) }
  function at(f) { stopClock(); target = null; seek(clamp(f, 0, LAST)) }
  update({ name: '' })
  return {
    el, attach, go, update, setText, orbit, at, release,
    set onFrame(fn) { onFrame = fn },
    get frame() { return frame }, get failed() { return failed }, get ready() { return Boolean(player) },
  }
}
