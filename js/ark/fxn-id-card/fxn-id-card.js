// The FXN ID card on defxn.com (owner, 2026-10-31). Layer: app. The site's one copy of FXN Browser's card module
// (ark-browser src/renderer/fxn-id-card/fxn-id-card.js), kept in the same shape so the two can become one shared module: the
// code below the PATHS block is the browser's, line for line, except where a comment says "site:". The design note is
// docs/design/auth/FXN-ID-CARD.md.
//
// The card is the fxn-3d studio document fxnbrowseridcardassembly (idcard01 laid landscape), exported as an embed and played by
// fxn-3d's web player; nothing here is Three.js. It is loaded with import() only when a page shows the card; nothing of it runs at
// page start.
//
// What ships, and where it lives on this site (PATHS below):
//   js/vendor/fxn-3d/fxn-embed.js        the player, generated by fxn-3d's scripts/embed-export.mjs; never edited by hand
//   assets/fxn-id-card/card-pack.js      the exported pack as base64 in a module (the browser's CSP cannot fetch it; the site keeps
//                                        the same file so both hosts load one pack the same way)
//   assets/fxn-id-card/card-states.js    the timeline's states, camera keys and print fields, generated with the pack
//   assets/fxn-id-card/card-settled.png  the settled card, see-through, for a browser without WebGL2
//   js/ark/fxn-id-card/fxn-id-card.css   the card's styles and the FXN ID view's, linked on first use
// The player reads its pack with fetch(url) (fxn-3d engine/sources/pack.mjs packFromUrl). For the length of the mount, window.fetch
// answers that one name from the bytes above and hands every other call to the real fetch.
//
// The timeline is a chain of states (card-states.js STATES): the build ends on welcome, then one state per create step (name, pin,
// password, word, words, confirm, done), then the account's master and open. go(state) moves the frame along the chain: forward plays
// each segment, back plays it in reverse at a faster pace, so every step animates back the way it came.
//
// The words and live values are 2D, drawn by the page at screen resolution, never baked: the name and "FXN ID" on the name plate, the
// PIN and password strength on the security plate, the chosen icon on the stamp, the recovery cells in the vault on the back. Each sits
// on its face through the document's own camera, sampled here with the player's rules (fxn-3d scripts/lib/anim-sample.mjs: curves,
// distance in log space, angles by the shortest arc), so it moves with the card. A print shows only while its face is toward the camera.
//
// The theme: the accent is painted at one hue (158 degrees); the canvas takes a CSS hue-rotate and saturate that turn it to the host's
// --fxn-idc-accent, while the grey metal does not move. The prints take --fxn-idc-accent directly. The host names that colour once,
// in fxn-id-card.css's host block (site: hsl(var(--primary)), the base hue every DEFXN theme builds on; the browser's --accent plays
// the same part there). Both follow a theme, mode or skin change while the card is shown (a MutationObserver on <html>).
//
//   const card = createFxnIdCard()
//   card.attach(host, { play, name })     build into host (play: false shows the welcome pose at once)
//   card.go(state)                        move to a state of the chain ('blank' is frame 0, the card before its build)
//   card.update({ name, pinGrade, passwordGrade, icon, total, picked })   the live values the prints show
//   card.setText({ name })                the name alone; empty shows "Your name"
//   card.orbit(yaw, pitch)                turns the view on top of the keyed camera (the FXN ID view's focus)
//   card.at(frame)                        holds one frame (proof sheets)
//   card.release()                        stops the player and frees its WebGL context
