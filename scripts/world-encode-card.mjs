#!/usr/bin/env node
/* The card encoder (docs/design/world-grammar/MESH.md). Build side, Node built-ins only; it shells out to macOS
   `sips` for image resizing and for a small resample that gives a texture's average colour, because Node has no
   image decoder and WASM is banned here.

   It reads the owner's 3D card (3d/cardfxn.glb, a glTF 2.0 binary from Tripo: 146 primitives, 146 materials,
   1.88 M triangles, 438 embedded images) ONCE and derives:
     1. one mesh blob, world/<cid>.mesh: the 146 primitives welded into ONE body (positions within 1e-4 of the
        bounds' diagonal are one vertex; normals and texture coordinates stay per face corner), duplicate and
        degenerate faces dropped; then the OUTER SKIN re-meshed as one closed shell (remesh(): a voxel grid, the
        outside flooded from the border, surface nets on the solid, Taubin smoothing, projection back onto the
        original skin with a crease snap, materials from the face each vertex lands on), so pieces inside or
        under other pieces are gone and no plate passes into another; that shell simplified by quadric edge
        collapse with its topology kept (the link condition), normals rebuilt with a 45 degree crease, vertices
        quantized to Int16, and a draw table of one entry per material carrying base colour, metal and roughness
        (MESH.md "The blob");
     2. at most 8 textures, world/<cid>.jpg, 256 x 256, for the materials with texture coordinates that cover the
        most triangle area; every material's base colour and metal-roughness images are averaged into its entry;
     3. the card's records in world/card.flx (MESH, TEX, PLACE), each read back through the card's OWN reader
        (js/world2/card-reader.mjs, generated by scripts/card-grammar-build.mjs from scripts/lib/card-grammar.mjs:
        one grammar per thing, owner 2026-10-29). This encoder generates no reader: a record the reader refuses is
        never written, and if the reader lacks a kind the refusal says to run the card grammar build first.
   Why: the first cut simplified each primitive alone, and every seam between parts tore (161 components and
   10,870 open edges). The second welded and simplified the glued parts as they were, and the owner still saw
   "many pieces glued together": plates passing into plates, pieces under pieces. The numbers are in MESH.md,
   "Defects found", and this encoder prints the same statistics at each stage so a rerun shows them.
   Rerunning on the same model writes the same bytes: every order is data order or content order, every name is
   the content's hash, and sips is deterministic for the same input and options (checked 2026-10-29).
   The glTF's own JSON chunk is read because glTF defines that format (JSON stays where another party defines it);
   nothing here writes JSON. WORLD_OUT=<dir> writes under that directory instead of the site (as world-encode.mjs).
   The mesh pipeline lives in flux/fxn-3d scripts/lib/mesh/* (gltf, weld, voxel, nets, project, qem, blob, stats): this file imports
   it, as the edit server does, so one library holds the geometry (centralize, don't duplicate); the shadow run of
   2026-10-29 proved the library writes the same bytes as the code it replaced.
   No tests until the owner has seen the screen. */
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { derive } from './world-encode.mjs';
import { rebuild } from './lib/world-card-rebuild.mjs';
import { readGlb, primitives, primArea, imageOf, factorsOf, linearMean, channelMean, toSrgbByte, bmpPixels, WELD, weld, clean, stats, statsLine, voxelSolid, remesh, simplifier, shade, writeBlob, boundsOf, sha } from './lib/fxn-3d.mjs';   /* the mesh library lives in flux/fxn-3d (scripts/lib/mesh/*); one door */

const SITE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = process.env.WORLD_OUT ? path.resolve(process.env.WORLD_OUT) : SITE;
const WORLD = path.join(OUT, 'world');
const READER = path.join(SITE, 'js', 'world2', 'card-reader.mjs');   /* the card's own reader; never written here */
const GLB = process.argv[2] ? path.resolve(process.argv[2]) : path.resolve(SITE, '..', '..', '3d', 'cardfxn.glb');

/* the budget: triangles over the whole card (up to 90,000 where quality needs it), bytes over the wire with
   textures, textures at most. The vertex count must fit Uint16 indices; the collapse continues until both hold. */
const TRI_TARGET = 60000, BYTE_BUDGET = 1.5 * 1024 * 1024, VERT_CAP = 65535, TEX_MAX = 8, TEX_SIZE = 256, JPEG_Q = 72;
const VIEW = 'auth';

/* the record kinds this encoder writes; the card reader must know them, or the card grammar build has not been run since they
   were added to its W closed set */
const KINDS = ['MESH', 'TEX', 'PLACE'];
/* number text (README.md): m is minus, p is the point; rounded to four places so the same number writes the same
   text whatever float noise the placement maths carries */
function num(v) {
  if (typeof v !== 'number' || !Number.isFinite(v)) throw new Error('number text needs a finite number, got ' + String(v));
  const s = String(Math.round(v * 1e4) / 1e4);
  if (!/^-?\d+(\.\d+)?$/.test(s)) throw new Error('number text cannot carry "' + s + '"');
  return s.replace('-', 'm').replace('.', 'p');
}


/* ---------- textures and material numbers through sips ---------- */
function pixels16(dir, files) {
  if (!files.length) return [];
  const outDir = path.join(dir, 'avg'); fs.mkdirSync(outDir, { recursive: true });
  execFileSync('sips', ['-z', '16', '16', '-s', 'format', 'bmp', ...files, '--out', outDir], { stdio: ['ignore', 'ignore', 'pipe'] });
  return files.map(f => {
    const b = fs.readFileSync(path.join(outDir, path.basename(f, path.extname(f)) + '.bmp'));
    return bmpPixels(b);
  });
}
function resized(dir, file) {
  const outDir = path.join(dir, 'tex'); fs.mkdirSync(outDir, { recursive: true });
  execFileSync('sips', ['-Z', String(TEX_SIZE), '-s', 'format', 'jpeg', '-s', 'formatOptions', String(JPEG_Q), file, '--out', outDir], { stdio: ['ignore', 'ignore', 'pipe'] });
  return fs.readFileSync(path.join(outDir, path.basename(file, path.extname(file)) + '.jpg'));
}

/* ---------- the blob (MESH.md, version 2) ---------- */

async function main() {
  const t0 = Date.now();
  /* the card reader, as it stands: refused before the minute of mesh work if it cannot read the card's kinds */
  const reader = await import(pathToFileURL(READER).href);
  const W = reader.LABELS.find(l => l.label === 'W'), missing = KINDS.filter(k => !W || !W.values.includes(k));
  if (missing.length) throw new Error('js/world2/card-reader.mjs does not read ' + missing.join(', ') + ': run node scripts/card-grammar-build.mjs first, which regenerates the reader from the labels that carry them');
  fs.mkdirSync(WORLD, { recursive: true });

  /* 1 the model, once; welded into one body; cleaned; measured */
  const g = readGlb(fs.readFileSync(GLB), GLB), prims = primitives(g);
  const srcTris = prims.reduce((s, p) => s + p.tris, 0);
  const body = weld(prims), cleaned = clean(body), before = stats(body);
  const line = statsLine;
  console.log(`world-encode-card: ${prims.length} primitives, ${srcTris} triangles, ${body.sourceVerts} vertices; welded at ${body.tol.toExponential(2)} (${WELD} of the diagonal) to ${body.X.length} vertices; dropped ${cleaned.degenerate} degenerate and ${cleaned.duplicate} duplicate faces`);
  console.log(line('welded input', before));
  /* the fourth cut: at most nine clean parts rebuilt from the voxel solid (scripts/lib/world-card-rebuild.mjs).
     CARD_SHELL=1 in the environment runs the third cut instead (the whole skin as one decimated shell). */
  const shellMode = process.env.CARD_SHELL === '1';
  const shell = shellMode ? remesh(body, console.log) : null;
  if (shell) console.log(line('closed shell', stats(shell)));
  const G = shellMode ? null : voxelSolid(body, console.log);

  /* 2 textures and material numbers: every material's base colour and metal-roughness images averaged (linear);
     the materials with texture coordinates, the TEX_MAX largest by area, keep a 256 x 256 JPEG of the base colour */
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'world-card-'));
  const byMaterial = new Map();
  prims.forEach(p => { const a = primArea(p); const e = byMaterial.get(p.material) || { area: 0, uv: false }; e.area += a; e.uv = e.uv || !!p.uv; byMaterial.set(p.material, e); });
  const materials = [...byMaterial.keys()].sort((a, b) => a - b);
  const files = [], fileOf = new Map();
  for (const mi of materials) for (const which of ['base', 'mr']) {
    const im = imageOf(g, mi, which); if (!im) continue;
    const f = path.join(tmp, which + mi + '.' + im.ext); fs.writeFileSync(f, im.bytes); files.push(f); fileOf.set(which + mi, f);
  }
  const px = pixels16(tmp, files), pxOf = new Map(); files.forEach((f, i) => pxOf.set(path.basename(f).split('.')[0], px[i]));
  const texturedMats = materials.filter(mi => byMaterial.get(mi).uv && fileOf.has('base' + mi)).sort((a, b) => byMaterial.get(b).area - byMaterial.get(a).area || a - b).slice(0, TEX_MAX);
  const textures = texturedMats.map((mi, slot) => { const bytes = resized(tmp, fileOf.get('base' + mi)); return { mi, slot, bytes, cid: sha(bytes) }; });
  fs.rmSync(tmp, { recursive: true, force: true });
  const entryOf = new Map();
  for (const mi of materials) {
    const F = factorsOf(g, mi), factor = F.base, mf = F.metal, rf = F.rough;
    const bp = pxOf.get('base' + mi), mp = pxOf.get('mr' + mi), tex = textures.find(t => t.mi === mi);
    const base = bp ? linearMean(bp) : [1, 1, 1];
    /* a textured draw multiplies its texture by the factor only; a flat one by the image's linear mean too */
    const rgb = (tex ? [1, 1, 1] : base).map((v, k) => toSrgbByte(v * factor[k]));
    const metal = Math.round(255 * Math.max(0, Math.min(1, (mp ? channelMean(mp, 2) : 1) * mf))), rough = Math.round(255 * Math.max(0, Math.min(1, (mp ? channelMean(mp, 1) : 1) * rf)));
    entryOf.set(mi, { rgba: [rgb[0], rgb[1], rgb[2], Math.round(255 * factor[3])], slot: tex ? tex.slot : 255, metal, rough });
  }

  let shaded, mesh, texBytes = textures.reduce((s, t) => s + t.bytes.length, 0), parts = null;
  if (shellMode) {
    /* 3 the collapse: to the triangle target, then on until the vertices fit Uint16 and the bytes fit the budget */
    const S = simplifier(shell);
    let target = TRI_TARGET, rounds = 0;
    for (;;) {
      S.collapseTo(target); rounds++;
      shaded = shade(shell);
      const entries = shaded.draws.map(d => Object.assign({ first: d.first, count: d.count }, entryOf.get(d.material)));
      mesh = writeBlob(shaded, shell.bounds, entries);
      if ((mesh.verts <= VERT_CAP && mesh.bytes.length + texBytes <= BYTE_BUDGET - 1024) || S.live() <= 1000) break;
      target = Math.floor(S.live() * .92);   /* a step down, and again: the collapse goes on from where it stands */
    }
    const after = stats(shell), refused = S.refused();
    console.log(line('output', after) + `; ${rounds} round(s), refused ${refused.link} link and ${refused.flip} flip collapses`);
  } else {
    /* 3 the rebuild: the parts, their proof, the parts table (printed every run) */
    const R = rebuild(body, G, null, console.log);
    shaded = R.mesh; parts = R;
    /* the parts are flat colours: no draw refers to a texture slot, so the decoder never fetches the texture; its
       record stays in card.flx (the world-grammar test expects MESH, TEX and PLACE) but it costs nothing on the wire */
    texBytes = 0;
    const entries = shaded.draws.map(d => Object.assign({ first: d.first, count: d.count }, entryOf.get(d.material)));
    mesh = writeBlob(shaded, boundsOf(shaded.pos), entries);
    console.log('  parts (name, level cell, area share, solids, material id, metal, rough, triangles written, closed: faces / components / open edges / non-manifold edges):');
    const total = R.parts.reduce((s, p) => s + (p.name === 'slab' ? 0 : p.cells), 0) || 1;
    for (const p of R.parts) { const e = entryOf.get(p.material) || { metal: 0, rough: 0 }; console.log(`    ${p.name.padEnd(7)} k${String(p.level).padStart(3)}  ${(p.cells / R.parts[0].cells * 100).toFixed(1).padStart(5)}%  x${p.solids}  m${String(p.material).padStart(3)}  metal ${(e.metal / 255).toFixed(2)} rough ${(e.rough / 255).toFixed(2)}  ${String(p.tris).padStart(5)} tris  closed ${p.faces} / ${p.components} / ${p.open} / ${p.nonManifold}`); }
    console.log(`  dropped features (level, cells, share of the card's columns): ${R.dropped.map(d => d.name + ' k' + d.level + ':' + d.cells + ' (' + (d.share * 100).toFixed(2) + '%)').join(', ')}`);
  }

  /* 4 write the blob and the textures by content id */
  const cid = sha(mesh.bytes);
  fs.writeFileSync(path.join(WORLD, cid + '.mesh'), mesh.bytes);
  textures.forEach(t => fs.writeFileSync(path.join(WORLD, t.cid + '.jpg'), t.bytes));

  /* 5 the records: the mesh, its textures, and the card's place in the auth view (auth-stage.js: height
     CH = HUB.R x 1.32, centre CY = CH / 2 + HUB.R / 2 over the kernel, turned to the view's yaw of -14 degrees) */
  const { cast } = derive(), HUB = cast.HUB, CH = HUB.R * 1.32, CY = CH * .5 + HUB.R * .5;
  const rec = [`WMESH-R${VIEW}-C${cid}-A${mesh.bytes.length}`];
  textures.forEach(t => rec.push(`WTEX-C${t.cid}-I${t.slot}`));
  rec.push(`WPLACE-R${VIEW}-X${num(HUB.c.x)}-Y${num(CY)}-Z${num(HUB.c.z)}-D${num(CH)}-Um14`);
  for (const r of rec) {
    if (!/^[\x21-\x7e]+$/.test(r)) throw new Error('a record must be printable ASCII with no spaces: ' + r);
    try { reader.readRecord(r); } catch (e) { throw new Error('the reader refuses a derived record, so card.flx is not written: ' + r + ' (' + e.message + ')'); }
  }
  const flx = rec.join('\n') + '\n';
  fs.writeFileSync(path.join(WORLD, 'card.flx'), flx);

  /* 6 the report: what was reached against the budget */
  const wire = mesh.bytes.length + texBytes + Buffer.byteLength(flx);
  console.log(`  ${srcTris} -> ${shaded.tris} triangles (target ${TRI_TARGET}), ${mesh.verts} vertices (cap ${VERT_CAP}), ${mesh.wide ? 'Uint32' : 'Uint16'} indices, ${shaded.draws.length} draws`);
  console.log(`  mesh ${mesh.bytes.length} bytes (${cid}.mesh), ${textures.length} texture(s) ${texBytes} bytes, card.flx ${Buffer.byteLength(flx)} bytes: ${wire} bytes over the wire (budget ${BYTE_BUDGET})${wire > BYTE_BUDGET ? ' OVER' : ''}`);
  console.log(`  textured materials: ${texturedMats.join(', ') || 'none'} (materials with texture coordinates: ${materials.filter(mi => byMaterial.get(mi).uv).length}); the rest draw their images' linear means`);
  console.log(`  place: height ${num(CH)} centre ${num(CY)} over the kernel at (${num(HUB.c.x)}, ${num(HUB.c.z)}); ${rec.length} records; ${((Date.now() - t0) / 1000).toFixed(1)} s`);
  if (parts && parts.parts.some(p => p.components !== p.solids || p.open > 0 || p.nonManifold > 0)) console.log('  a part is NOT closed (one component per solid, no open or non-manifold edge): see the table above');
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) main().catch(e => { console.error('world-encode-card: ' + e.message); process.exit(1); });
