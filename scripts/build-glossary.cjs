#!/usr/bin/env node
/* =====================================================================
   GLOSSARY BUILD -- docs/glossary.md -> js/content/glossary.js (ArkGlossary)
   ---------------------------------------------------------------------
     node scripts/build-glossary.cjs           writes js/content/glossary.js
     node scripts/build-glossary.cjs --check   writes nothing; exits 1 when the
                                               module no longer matches the doc
                                               (tests/ark-blocks-adapter.cjs runs it)

   docs/glossary.md is the one place a term is defined. The Ark `term` block and
   [[term]] markup (js/ark/blocks.js) read the definitions from this generated
   module, so a page never types a definition and the site never disagrees with
   the glossary. It is a derived build output, not a store: nothing writes it but
   this script, and it is rebuilt from the doc, never edited.

   What is derived, by the doc's own structure (not by a list of terms):
     - an entry is a paragraph that opens with **Term**, then " — ", then the
       definition; the key is the bold term, lowercased;
     - a parenthetical between the term and the dash qualifies the term and stays
       with it ("Signer (of a launch)");
     - inside the definition, markdown links keep their words, code spans lose
       their backticks, and a parenthetical that stands as a sentence of its own
       after a full stop (the doc's dated history notes) is left out, as is a
       closing "See ..." sentence: a tooltip says what the word means now.
   A word written in another form is marked up as [[label|key]] by the page.
   ===================================================================== */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = 'docs/glossary.md';
const OUT = 'js/content/glossary.js';

function plain(markdown) {
  return markdown
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/\*\*([^*]+)\*\*/g, '$1');
}

function definitionOf(raw) {
  let text = raw.trim();
  // A history note: "... sentence. (Until 2026-10-19 this read ...)" -- a sentence of its own.
  let previous;
  do { previous = text; text = text.replace(/([.!?])\s*\((?:[^()]|\([^()]*\))*\)\s*/g, '$1 ').trim(); } while (text !== previous);
  text = plain(text);
  // A closing pointer elsewhere: "... See [resolvers](protocol/resolvers.md)." (link words kept above)
  text = text.replace(/(^|[.!?]\s+)See [^.]*\.\s*$/, '$1').trim();
  return text.replace(/\s+/g, ' ').trim();
}

function parse(markdown) {
  const entries = [];
  for (const paragraph of markdown.split(/\n\s*\n/)) {
    const m = /^\*\*([^*]+)\*\*(\s*\([^)]*\))?\s+—\s+([\s\S]+)$/.exec(paragraph.trim());
    if (!m) continue;
    const term = (m[1] + (m[2] ? ' ' + m[2].trim() : '')).trim();
    const definition = definitionOf(m[3]);
    if (!definition) continue;
    entries.push({ key: m[1].trim().toLowerCase(), term, definition: definition.charAt(0).toUpperCase() + definition.slice(1) });
  }
  return entries;
}

function moduleSource(entries) {
  const lines = entries.map((entry) => '    ' + JSON.stringify(entry.key) + ': { term: ' + JSON.stringify(entry.term) + ', definition: ' + JSON.stringify(entry.definition) + ' }');
  return '/* Generated by scripts/build-glossary.cjs from ' + SOURCE + '. Do not edit: change the glossary,\n' +
    '   then run `node scripts/build-glossary.cjs`. Read by js/ark/blocks.js (the Ark term block and\n' +
    '   [[term]] markup). ' + entries.length + ' terms. */\n' +
    'var ArkGlossary = {\n' +
    '  source: ' + JSON.stringify(SOURCE) + ',\n' +
    '  map: {\n' + lines.join(',\n') + '\n  }\n' +
    '};\n';
}

function build() {
  return moduleSource(parse(fs.readFileSync(path.join(ROOT, SOURCE), 'utf8')));
}

function main() {
  const check = process.argv.includes('--check');
  const next = build();
  const file = path.join(ROOT, OUT);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (check) {
    if (current === next) { console.log('[build-glossary] ok ' + OUT); return; }
    console.error('[build-glossary] DRIFT ' + OUT + (current === null ? ' (missing)' : ' no longer matches ' + SOURCE) + '; run node scripts/build-glossary.cjs');
    process.exit(1);
  }
  if (current !== next) fs.writeFileSync(file, next);
  console.log('[build-glossary] ' + (current === next ? 'unchanged ' : 'wrote ') + OUT);
}

module.exports = { parse, build, SOURCE, OUT };

if (require.main === module) main();
