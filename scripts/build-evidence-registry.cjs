#!/usr/bin/env node
/* =====================================================================
   EVIDENCE REGISTRY BUILD -- docs/evidence/registry.md -> js/content/evidence-registry.js
   ---------------------------------------------------------------------
     node scripts/build-evidence-registry.cjs           writes js/content/evidence-registry.js
     node scripts/build-evidence-registry.cjs --check   writes nothing; exits 1 when the module
                                                        no longer matches the registry
                                                        (tests/home-blocks.cjs runs it)

   docs/evidence/registry.md is the one place a benchmark claim is promoted. A public page that
   quotes a benchmark number reads it from this generated module, so a page can never show a
   figure the registry does not carry, nor call a record verified that the registry does not.
   Named regression (2026-10-19, docs/ux-audit/pages-ux-a.md): the home page's benchmark tiles
   showed 643,632 swaps/s, 69,895 transfers/s and 6,044,992 records/s as "BENCH-013", while the
   registry's BENCH-013 row is one machine, no network, and carries none of those figures --
   and /concept/spec, which states only what the registry verifies, read as a contradiction.

   What is derived, by the registry's own structure (not by a list of ids):
     - a benchmark record is a table row whose first cell is BENCH-nnn; its cells are the id,
       the claim, the status and the evidence;
     - `verified` is the registry's own word: the status says "verified" and not "unverified"
       (the same rule tests/concept-spec-current.cjs applies to /concept/spec);
     - the evidence keeps its words: markdown links keep their text, emphasis and code marks go.
   It is a derived build output, not a store: nothing writes it but this script.
   ===================================================================== */
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const SOURCE = 'docs/evidence/registry.md';
const OUT = 'js/content/evidence-registry.js';

function plain(markdown) {
  return markdown
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/\s+/g, ' ')
    .trim();
}

const isVerified = (status) => /\bverified\b/i.test(status) && !/\bunverified\b/i.test(status);

function parse(markdown) {
  const records = [];
  for (const line of markdown.split('\n')) {
    const m = /^\|\s*(BENCH-\d{3})\s*\|([^|]*)\|([^|]*)\|(.*)\|\s*$/.exec(line);
    if (!m) continue;
    const status = plain(m[3]);
    records.push({ id: m[1], claim: plain(m[2]), status, verified: isVerified(status), evidence: plain(m[4]) });
  }
  return records;
}

function moduleSource(records) {
  const lines = records.map((r) => '    ' + JSON.stringify(r.id) + ': { claim: ' + JSON.stringify(r.claim) + ', status: ' + JSON.stringify(r.status) +
    ', verified: ' + r.verified + ',\n      evidence: ' + JSON.stringify(r.evidence) + ' }');
  return '/* Generated by scripts/build-evidence-registry.cjs from ' + SOURCE + '. Do not edit: change the\n' +
    '   registry, then run `node scripts/build-evidence-registry.cjs`. Read by js/pages/home.js, which\n' +
    '   quotes a benchmark figure only when a verified record here carries it. ' + records.length + ' benchmark records,\n' +
    '   ' + records.filter((r) => r.verified).length + ' verified. */\n' +
    'var ArkEvidence = {\n' +
    '  source: ' + JSON.stringify(SOURCE) + ',\n' +
    '  benchmarks: {\n' + lines.join(',\n') + '\n  }\n' +
    '};\n';
}

function build() {
  return moduleSource(parse(fs.readFileSync(path.join(ROOT, SOURCE), 'utf8')));
}

function main() {
  const check = process.argv.includes('--check');
  const next = build();
  const file = path.join(ROOT, OUT);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (check) {
    if (current === next) { console.log('[build-evidence-registry] ok ' + OUT); return; }
    console.error('[build-evidence-registry] DRIFT ' + OUT + (current === null ? ' (missing)' : ' no longer matches ' + SOURCE) + '; run node scripts/build-evidence-registry.cjs');
    process.exit(1);
  }
  if (current !== next) fs.writeFileSync(file, next);
  console.log('[build-evidence-registry] ' + (current === next ? 'unchanged ' : 'wrote ') + OUT);
}

module.exports = { parse, build, isVerified, SOURCE, OUT };

if (require.main === module) main();
