#!/usr/bin/env node
/* Writes css/flux-themes.css from the Dead Ark SDK, the canonical home of the DEFXN
   palette since 2026-10-19 (AGENTS.md: the SDK theme is the source of truth;
   docs/ux-audit/brand.md D1/D2).

     node scripts/build-flux-themes.cjs           write css/flux-themes.css
     node scripts/build-flux-themes.cjs --check   exit 1 if it differs from the SDK

   The five families (Ember, Tide, Moss, Dune, Dusk), their OKLCH role ladders, the
   per-palette swatches and the role-alias block are generated by the SDK's
   role-ladder module (design/deadark-sdk/src/theme/role-ladder.ts), ported from this
   script byte for byte: getDeadArkRoleLadderPublishedCss() reproduces the file this
   script used to generate, verified by its sha256 (DEADARK_ROLE_LADDER_LEGACY_CSS_SHA256); the published form below adds only selectors.
   Every palette is selectable under its OLD key (ghost, glacier, clay, ...) and its published
   name (ember, ember-light, defxn-tide, ... -- docs/ux-audit/brand.md D3): the sheet carries a
   twin selector per palette with identical declarations, so a stale cached page or an old
   stored value still paints. Old keys are mapped to published names on READ only
   (js/bootstrap.js, js/content/theme-ids.js); nothing stored is rewritten.
   To change a colour, change the SDK family and republish the SDK; never edit the
   output, and never re-grow a generator here (one source, not two).

   Which SDK: the installed @deadark/sdk (synced by `npm run sync:ark`) once it exports
   the role-ladder module (0.2.41 and later, which adds the published names); until that version is packed and synced,
   the workspace SDK at design/deadark-sdk. The script says which one it read. */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { pathToFileURL } = require('node:url');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'css', 'flux-themes.css');
const WORKSPACE_SDK = path.resolve(ROOT, '..', '..', 'design', 'deadark-sdk', 'dist', 'theme', 'index.js');

async function loadSdk() {
  const tried = [];
  try {
    const installed = await import('@deadark/sdk/theme');
    if (typeof installed.getDeadArkRoleLadderPublishedCss === 'function') return { sdk: installed, from: '@deadark/sdk (installed)' };
    tried.push('@deadark/sdk (installed) has no role-ladder module: older than 0.2.41');
  } catch (error) { tried.push(`@deadark/sdk (installed): ${error.code || error.message}`); }
  if (fs.existsSync(WORKSPACE_SDK)) {
    const workspace = await import(pathToFileURL(WORKSPACE_SDK).href);
    if (typeof workspace.getDeadArkRoleLadderPublishedCss === 'function') return { sdk: workspace, from: path.relative(ROOT, WORKSPACE_SDK) };
    tried.push(`${WORKSPACE_SDK} has no role-ladder module`);
  } else tried.push(`${WORKSPACE_SDK} is missing`);
  const error = new Error(`no Dead Ark SDK with the role-ladder palette was found\n  tried:   ${tried.join('\n           ')}\n  remedy:  run npm run sync:ark once @deadark/sdk 0.2.41+ is packed, or build design/deadark-sdk (npm run build there)`);
  error.refusal = true;
  throw error;
}

async function main() {
  const { sdk, from } = await loadSdk();
  const css = sdk.getDeadArkRoleLadderPublishedCss();
  const sha = crypto.createHash('sha256').update(css).digest('hex');
  // the palette values are guarded by the legacy file's declared hash; the published file adds selectors only
  const legacySha = crypto.createHash('sha256').update(sdk.getDeadArkRoleLadderLegacyCss()).digest('hex');
  if (sdk.DEADARK_ROLE_LADDER_LEGACY_CSS_SHA256 && legacySha !== sdk.DEADARK_ROLE_LADDER_LEGACY_CSS_SHA256) {
    throw new Error(`the SDK's role-ladder CSS hashes to ${legacySha}, not its declared ${sdk.DEADARK_ROLE_LADDER_LEGACY_CSS_SHA256}\n  remedy:  rebuild design/deadark-sdk; a palette change must update the declared hash in the same change`);
  }
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : null;
  if (process.argv.includes('--check')) {
    if (current !== css) { console.error(`css/flux-themes.css differs from the SDK palette (${from}). Run: node scripts/build-flux-themes.cjs`); process.exit(1); }
    console.log(`css/flux-themes.css matches the SDK palette (${from}, sha256 ${sha.slice(0, 12)})`);
    return;
  }
  if (current !== css) fs.writeFileSync(OUT, css);
  console.log(`${current === css ? 'unchanged' : 'wrote'} css/flux-themes.css from ${from} (sha256 ${sha.slice(0, 12)}, ${sdk.DEADARK_ROLE_LADDER_FAMILIES.length * 2} palettes)`);
}

main().catch((error) => { console.error(error.message); process.exit(2); });
