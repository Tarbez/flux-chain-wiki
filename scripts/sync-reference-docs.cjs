/* Derive the reader allowlist from public page links and their local Markdown
   references. Never accept an arbitrary document/file path from a route query.

   What it writes (all generated, none hand-edited; JS, not JSON, like the rest of js/content):
     js/ark/reference-docs.js            the allowlist (every page loads it; ids only)
     js/content/reference-index.js       the reader's index: per document its title, sha256 and origins
     js/content/reference/<doc>.js       one file per document (docs/protocol/agreements.md ->
                                         js/content/reference/protocol/agreements.js): its text and sha256

   /reference loads the index, then ONLY the file of the document it shows (js/pages/reference.js,
   through ArkUI.loadScript). Until 2026-10-20 every document was in one file, 150.8 KB gz on every visit.

   Usage:
     node scripts/sync-reference-docs.cjs           write the snapshots
     node scripts/sync-reference-docs.cjs --check   write nothing; exit 1 naming what differs and the remedy
   tests/reference-reader.cjs runs the check, so a stale snapshot fails the unit suite. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const ROOT = path.resolve(__dirname, '..');
const REMEDY = 'node scripts/sync-reference-docs.cjs';
const DOC = /^docs\/(?:[a-z0-9-]+\/)*[a-z0-9-]+\.md$/;
const TEXT_DIR = 'js/content/reference';
const INDEX_FILE = 'js/content/reference-index.js';
const DOCS_FILE = 'js/ark/reference-docs.js';
/* Segment names the host rewrites by (vercel.json; stripRouteSegments in api/lib/render-core.mjs): a file under a
   directory of one of these names would be fetched from the wrong place. A document id that would put one in a file's
   path is refused here, at generation, not found as a blank reader in production. */
const RESERVED_SEGMENTS = ['js', 'css', 'assets', 'docs', 'legacy', 'api'];

/* The path a document's text file is published at. Derived, never stored: the reader and the generator both call it. */
function textFile(doc) {
  const relative = doc.replace(/^docs\//, '').replace(/\.md$/, '');
  const segments = relative.split('/');
  const bad = segments.find((segment) => RESERVED_SEGMENTS.includes(segment));
  if (bad) throw new Error('Reference document ' + doc + ' has a path segment named "' + bad + '", which the host rewrites; rename it or the directory.');
  return TEXT_DIR + '/' + relative + '.js';
}

/* The document's title: its first `# ` line. The reader once re-derived this from the text; it reads the index now. */
function titleOf(text) { return (text.match(/^#\s+(.+)$/m) || [])[1] || 'Reference'; }

function derive(root = ROOT) {
  const found = new Map([['docs/protocol/resolvers.md', new Set(['seed'])]]);
  const note = (doc, origin) => { if (!found.has(doc)) found.set(doc, new Set()); found.get(doc).add(origin); };
  for (const dir of ['js/pages', 'js/content/manifests']) {
    for (const file of fs.readdirSync(path.join(root, dir)).filter(x=>x.endsWith('.js'))) {
      /* Only what a page can link counts, never what a comment mentions. Until 2026-10-19 a code
         comment citing an internal audit (docs/ux-audit/*.md) made that audit a public reference
         document -- with an absolute local path in it (tests/ark-vendor.cjs caught it). Block
         comments and whole-line // comments are removed before matching. */
      const code = fs.readFileSync(path.join(root, dir, file), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
      for (const match of code.matchAll(/docs\/[a-z0-9/.-]+\.md/g)) note(match[0], dir + '/' + file);
    }
  }
  /* a Map iterates what is added while it is walked: a document linked only from another one is found too */
  for (const doc of found.keys()) {
    if (!DOC.test(doc) || !fs.existsSync(path.join(root, doc))) throw new Error('Missing public reference: '+doc);
    const text = fs.readFileSync(path.join(root,doc),'utf8');
    for (const match of text.matchAll(/\]\(([^)\s]+\.md)(?:#[^)]*)?\)/g)) {
      const next = path.posix.normalize(path.posix.join(path.posix.dirname(doc),match[1]));
      if (DOC.test(next) && fs.existsSync(path.join(root,next))) note(next, doc);
    }
  }
  const docs = [...found.keys()].sort();
  const outputs = new Map();
  outputs.set(DOCS_FILE, '/* Generated by scripts/sync-reference-docs.cjs from public canonical links. */\nArkUI.referenceDocs = Object.freeze('+JSON.stringify(docs,null,2)+');\n');
  const index = [];
  const seenFiles = new Map();
  for (const doc of docs) {
    const text = fs.readFileSync(path.join(root,doc),'utf8');
    const sha256 = crypto.createHash('sha256').update(text).digest('hex');
    const file = textFile(doc);
    if (seenFiles.has(file)) throw new Error('Reference documents ' + seenFiles.get(file) + ' and ' + doc + ' would share the file ' + file);
    seenFiles.set(file, doc);
    outputs.set(file, '/* Generated from ' + doc + ' by scripts/sync-reference-docs.cjs. */\nArkUI.referenceText = ArkUI.referenceText || {};\nArkUI.referenceText['+JSON.stringify(doc)+'] = Object.freeze({text:'+JSON.stringify(text)+',sha256:'+JSON.stringify(sha256)+'});\n');
    index.push('  '+JSON.stringify(doc)+': {file:'+JSON.stringify(file)+',title:'+JSON.stringify(titleOf(text))+',sha256:'+JSON.stringify(sha256)+',origins:'+JSON.stringify([...found.get(doc)].sort())+'}');
  }
  outputs.set(INDEX_FILE, '/* Generated by scripts/sync-reference-docs.cjs: each approved reference document\'s text file, title, sha256 and the files that link it.\n   The text is not here; js/pages/reference.js loads js/content/reference/<document>.js for the one it shows. */\nArkUI.referenceIndex = Object.freeze({\n'+index.join(',\n')+'\n});\n');
  return {docs, outputs};
}

/* Every .js file under js/content/reference/, as site-relative paths: what the generator owns and may delete. */
function existingTextFiles(root) {
  const out = [], walk = (dir) => {
    if (!fs.existsSync(path.join(root, dir))) return;
    for (const entry of fs.readdirSync(path.join(root, dir), {withFileTypes: true})) {
      const rel = dir + '/' + entry.name;
      if (entry.isDirectory()) walk(rel); else out.push(rel);
    }
  };
  walk(TEXT_DIR);
  return out;
}

/* What differs between the snapshots on disk and what the sources derive: [] when current. */
function check(root = ROOT) {
  const {outputs} = derive(root), problems = [];
  for (const [file, content] of outputs) {
    const full = path.join(root, file);
    if (!fs.existsSync(full)) problems.push('missing: ' + file);
    else if (fs.readFileSync(full, 'utf8') !== content) problems.push('stale: ' + file);
  }
  for (const file of existingTextFiles(root)) if (!outputs.has(file)) problems.push('orphan (its document is no longer approved): ' + file);
  if (fs.existsSync(path.join(root, 'js/content/reference-text.js'))) problems.push('orphan (the one-file snapshot this generator replaced): js/content/reference-text.js');
  return problems;
}

function main(root = ROOT) {
  const {docs, outputs} = derive(root);
  for (const [file, content] of outputs) {
    fs.mkdirSync(path.dirname(path.join(root, file)), {recursive: true});
    fs.writeFileSync(path.join(root, file), content);
  }
  for (const file of existingTextFiles(root)) if (!outputs.has(file)) fs.rmSync(path.join(root, file));
  fs.rmSync(path.join(root, 'js/content/reference-text.js'), {force: true});
  console.log('Derived '+docs.length+' approved canonical reference documents: one text file each under '+TEXT_DIR+'/ and an index.');
}

if (require.main === module) {
  if (process.argv.includes('--check')) {
    const problems = check();
    if (problems.length) {
      console.error('The reference snapshots are out of date with their canonical Markdown or page links:\n  ' + problems.join('\n  ') + '\nRemedy: run `' + REMEDY + '` and review the diff (the generated files are never hand-edited).');
      process.exitCode = 1;
    } else console.log('Reference snapshots are current.');
  } else main();
}
module.exports = {main, check, derive, textFile, titleOf, REMEDY};
