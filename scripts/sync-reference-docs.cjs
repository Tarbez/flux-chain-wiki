/* Derive the reader allowlist from public page links and their local Markdown
   references. Never accept an arbitrary document/file path from a route query. */
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
function main() {
  const root = path.resolve(__dirname, '..'), found = new Set(['docs/protocol/resolvers.md']);
  for (const dir of ['js/pages', 'js/content/manifests']) {
    for (const file of fs.readdirSync(path.join(root, dir)).filter(x=>x.endsWith('.js'))) {
      /* Only what a page can link counts, never what a comment mentions. Until 2026-10-19 a code
         comment citing an internal audit (docs/ux-audit/*.md) made that audit a public reference
         document -- with an absolute local path in it (tests/ark-vendor.cjs caught it). Block
         comments and whole-line // comments are removed before matching. */
      const code = fs.readFileSync(path.join(root, dir, file), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '').replace(/^\s*\/\/.*$/gm, '');
      for (const match of code.matchAll(/docs\/[a-z0-9/.-]+\.md/g)) found.add(match[0]);
    }
  }
  for (const doc of found) {
    if (!/^docs\/(?:[a-z0-9-]+\/)*[a-z0-9-]+\.md$/.test(doc) || !fs.existsSync(path.join(root, doc))) throw new Error('Missing public reference: '+doc);
    const text = fs.readFileSync(path.join(root,doc),'utf8');
    for (const match of text.matchAll(/\]\(([^)\s]+\.md)(?:#[^)]*)?\)/g)) {
      const next = path.posix.normalize(path.posix.join(path.posix.dirname(doc),match[1]));
      if (/^docs\/(?:[a-z0-9-]+\/)*[a-z0-9-]+\.md$/.test(next) && fs.existsSync(path.join(root,next))) found.add(next);
    }
  }
  fs.writeFileSync(path.join(root,'js/ark/reference-docs.js'), '/* Generated by scripts/sync-reference-docs.cjs from public canonical links. */\nArkUI.referenceDocs = Object.freeze('+JSON.stringify([...found].sort(),null,2)+');\n');
  const documents = Object.fromEntries([...found].sort().map(doc => {
    const text = fs.readFileSync(path.join(root,doc),'utf8');
    return [doc,{text,sha256:crypto.createHash('sha256').update(text).digest('hex')}];
  }));
  fs.writeFileSync(path.join(root,'js/content/reference-text.js'),'/* Generated from canonical Markdown by scripts/sync-reference-docs.cjs. */\nArkUI.referenceText = Object.freeze('+JSON.stringify(documents,null,2)+');\n');
  console.log('Derived '+found.size+' approved canonical reference documents and their source-owned text snapshots.');
}
if (require.main === module) main();
module.exports = {main};
