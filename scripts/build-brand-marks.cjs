/* Brand marks as CSS masks. GENERATED output: css/brand-marks.css.
   The marks are single-colour shapes (assets/brand/*.png, alpha only). They are
   embedded as data: URIs because a CSS mask loaded from file:// is blocked as
   cross-origin, and this site must open with a double-click. Painted with
   background:currentColor, so a mark takes the ink of whatever it sits in, in
   every palette. Edit the PNGs, then run: node scripts/build-brand-marks.cjs */
const fs = require('node:fs');
const path = require('node:path');
const MARKS = { defxn: 'defxn-mark.png', fxn: 'fxn-mark.png' };
const dir = path.join(__dirname, '..', 'assets', 'brand');
let css = '/* GENERATED by scripts/build-brand-marks.cjs. Do not edit by hand. */\n:root {\n';
for (const [name, file] of Object.entries(MARKS))
  css += `  --mark-${name}:url("data:image/png;base64,${fs.readFileSync(path.join(dir, file)).toString('base64')}");\n`;
css += '}\n';
css += `/* .brand-mark is the mask; size it with width/height, colour it with color. */
.brand-mark {display:inline-block;flex:0 0 auto;background:currentColor;vertical-align:middle;
  -webkit-mask:var(--mark) center/contain no-repeat;mask:var(--mark) center/contain no-repeat;}
.brand-mark-defxn {--mark:var(--mark-defxn);}
.brand-mark-fxn {--mark:var(--mark-fxn);}
`;
fs.writeFileSync(path.join(__dirname, '..', 'css', 'brand-marks.css'), css);
console.log('wrote css/brand-marks.css (' + Object.keys(MARKS).length + ' marks)');
